def 维持课程感官(身子):
    """课纲作用期中, 每滴答把感官输入叠加在节律环境上。"""
    身子.环境["光"] = min(
        亮度上限,
        身子.环境.get("光", 50) + 150.0
    )
    身子.环境["声"] = min(
        声响上限,
        身子.环境.get("声", 45) + 12.0
    )
    身子.环境["力"] = min(
        50.0,
        身子.环境.get("力", 10) + 5.0
    )


def 通道输入(身子, 条目, 滴答计数):
    """把一条课纲条目编码进环境变量(感官通道)。"""

    大类 = 条目.get("category", "")
    主题 = 条目.get("topic", "")
    内容 = 条目.get("content", "")

    # 默认: 文字输入 = 视觉
    身子.环境["光"] = min(
        亮度上限,
        身子.环境.get("光", 50) + 150.0
    )

    # 语言/历史/语文/社会/情绪/关系 朗读成分也多
    可听大类 = {"语言", "语文", "历史", "地理", "社会", "情绪", "关系", "英语", "政治"}
    if 大类 in 可听大类:
        身子.环境["声"] = min(
            声响上限,
            身子.环境.get("声", 45) + 15.0
        )

    # 手工/体育/实验 → 触觉/力
    触觉大类 = {"运动", "艺术", "生活常识"}
    if 大类 in 触觉大类 or "实验" in 主题:
        身子.环境["力"] = min(
            50.0,
            身子.环境.get("力", 10) + 8.0
        )

    return {
        "topic": 主题, "category": 大类,
        "channel": "视觉+听觉" if 大类 in 可听大类 else
                   "视觉+触觉" if 大类 in 触觉大类 else "视觉",
        "snippet": 内容[:80],
    }


def 跑学习器(年龄列=None, 每年滴答数=480, 分钟每滴答=3, 输出间隔=60):
    if 年龄列 is None:
        年龄列 = [0.5, 4.0, 14.0, 18.0]

    节律映射 = {
        0.5: None,    # 待交叉验证时同步新身体节律接口
        4.0: None,
        14.0: None,
        18.0: 十八岁节律,
    }

    结果集 = {}

    for 年龄 in 年龄列:
        节律 = 节律映射.get(年龄)
        if 节律 is None:
            print(f"年龄 {年龄}: 节律未配置, 跳过 (交叉验证时从身体同步)")
            continue

        print(f"\n{'='*70}")
        print(f"年龄 {年龄}")
        print(f"节律段数: {len(节律)}, 滴答={分钟每滴答}分钟")

        # 1. 取课纲
        池 = 年龄门禁实例.查询(年龄, 上限数=100)
        if "error" in (池[0] if 池 else {}):
            print(f"年龄 {年龄}: 年龄门禁查询出错: {池[0]}")
            池 = []
        print(f"  课纲池: {len(池)} 条")
        if 池:
            分类统计 = defaultdict(int)
            for 条目 in 池:
                分类统计[条目.get("category", "?")] += 1
            print(f"  课纲类别分布: {dict(分类统计)}")

        # 2-3. 跑学习者 (身子 + 课纲走感官)
        身子 = 身体(节点数=24, 种子=1)
        身子.环境 = {"光": 50.0, "声": 45.0, "力": 10.0, "温": 295.0}
        服务序列 = []
        通道日志 = []

        池索引 = 0
        条目滴答数 = 40
        当前课纲滴答余量 = 0
        当前主题 = ""

        for 滴答序 in range(每年滴答数):
            # 按节奏推一条课纲
            if 池 and 滴答序 % 条目滴答数 == 0:
                条目 = 池[池索引 % len(池)]
                池索引 += 1
                信息 = 通道输入(身子, 条目, 滴答序)
                信息["tick"] = 滴答序
                当前主题 = 条目.get("topic", "")
                通道日志.append(信息)
                当前课纲滴答余量 = 条目滴答数
            elif 当前课纲滴答余量 > 0:
                维持课程感官(身子)
                当前课纲滴答余量 -= 1

            身子.推进()

        # 汇总
        总服务 = sum(getattr(身子, '已服务数', {}).values()) or 1
        结果集[年龄] = {
            "age": 年龄,
            "pool_size": len(池),
            "channel_log_count": len(通道日志),
            "channel_mix": _通道混合(通道日志),
        }

        print(f"\n  [通道混合] 课纲进来走什么通道")
        for 通道, 数 in 结果集[年龄]["channel_mix"].items():
            print(f"    {通道}: {数}")

        print(f"\n  [课纲] 实际推送给身体的通道日志数: {len(通道日志)}")

    return 结果集


def _通道混合(日志):
    混 = defaultdict(int)
    for 信息 in 日志:
        混[信息["channel"]] += 1
    return dict(混)


