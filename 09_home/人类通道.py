        self.n_hidden = n_hidden
        self.n_audio = n_audio
        self.有人在 = False
        self.人类名字 = None
        self.上次输入时间 = None
        self.当前人类信号 = [0.0] * n_hidden
        self.当前听觉信号 = [0.0] * n_audio
        self.互动历史 = []
        self.互动总数 = 0

