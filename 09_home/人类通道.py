        # 人类通过反复互动学会理解洛神的表达
        # 意图类型通过概念激活模式 + 情感状态 + surprise自然涌现
        self.表达历史 = []
        self.上次表达拍 = 0

        # ── 感知渴望：感官离线时的主动请求 ──
        # 洛神的感官（视网膜/耳蜗）离线时，会产生感知渴望
        # 渴望强度随离线时间增长——就像人长时间待在黑暗中会渴望看到光
        self.感官离线时间 = {"光": 0, "声": 0, "温": 0, "力": 0}
        self.感知渴望阈值 = 10  # 离线10拍后开始产生渴望
        self.上次请求拍 = -100  # 上次发出感知请求的拍数

