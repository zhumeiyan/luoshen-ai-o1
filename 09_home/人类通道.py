    # 接收方向（人类→洛神）
    # ═══════════════════════════════════════════════════════════════

    def 接收(self, 文本=None, 语音特征=None, 存在=True, 名字=None):
        """接收人类输入——把人类放进精卫公式。

        参数：
          文本: 人类输入的文本（可选）
          语音特征: 人类语音的频谱特征（可选，8维）
          存在: 人类是否在场（默认True）
          名字: 人类的名字（可选，用于绑定）

        返回：
          dict包含：
            人类信号: b向量（n_hidden维）
            听觉信号: 语音特征（n_audio维）
            有人在: bool
            情感强度: float
            感官描述: 人类描述的感官场景（可选）
        """
        self.有人在 = 存在
        if 名字:
            self.人类名字 = 名字
        if 存在:
            self.上次输入时间 = time.time()
            self.无互动拍数 = 0

        if not 存在:
            self.当前人类信号 = [0.0] * self.n_hidden
            self.当前听觉信号 = [0.0] * self.n_audio
            return {
                "人类信号": self.当前人类信号,
                "听觉信号": self.当前听觉信号,
                "有人在": False,
                "情感强度": 0.0,
                "感官描述": None,
            }

        # ── 有人在：构建人类信号向量 ──
        信号 = [0.0] * self.n_hidden
        情感强度 = 0.0
        感官描述结果 = None

        if 文本:
            # 文本→向量：字符频率分析
            char_count = {}
            for ch in 文本:
                if ch in self.char_map:
                    char_count[ch] = char_count.get(ch, 0) + 1

            total_chars = max(len(文本), 1)
            for ch, count in char_count.items():
                weight = count / total_chars
                cv = self.char_map[ch]
                for d in range(self.n_hidden):
                    信号[d] += cv[d] * weight

            max_val = max(abs(v) for v in 信号) if any(v != 0 for v in 信号) else 1.0
            if max_val > 0:
                信号 = [v / max_val for v in 信号]

            for word, val in self.情感词.items():
                if word in 文本:
                    情感强度 += val
            情感强度 = max(-1.0, min(1.0, 情感强度))

            # ── 感官描述转译：检查文本中是否包含感官描述 ──
            感官描述结果 = self.感官描述转译(文本)

        if 语音特征:
            self.当前听觉信号 = list(语音特征[:self.n_audio])
        else:
            self.当前听觉信号 = [0.0] * self.n_audio

        # 存在感基底信号
        if not 文本 and not 语音特征:
            信号 = [0.05] * self.n_hidden

        self.当前人类信号 = 信号
        self.互动总数 += 1
        self.互动历史.append({
            "kind": "text" if 文本 else ("voice" if 语音特征 else "presence"),
            "情感强度": 情感强度,
            "时间": self.上次输入时间,
        })

        if len(self.互动历史) > 1000:
            self.互动历史 = self.互动历史[-1000:]

        return {
            "人类信号": self.当前人类信号,
            "听觉信号": self.当前听觉信号,
            "有人在": True,
            "情感强度": 情感强度,
            "感官描述": 感官描述结果,
        }

    def 感官描述转译(self, 文本):
        """感官描述转译：人类文本描述→洛神感官信号。

        人类用自然语言描述世界（"外面很亮"、"有人在说话"），
        洛神转译成和视网膜/耳蜗/身体环境相同维度的信号。

        精卫公式解读（感官描述版）：
          a = 洛神当前的感官状态（大多数时候离线=零）
          b = 人类描述的感官场景
          Δ = b - a = 人类带来的新感官信息
          Σ = a + b = 联合感知
          ⊗ = 累积的感知历史 → 洛神通过人类描述构建的世界认知
          τ读⊗ → 浮出所见 = 洛神"想象"中的世界

        生物学类比：盲人通过别人的描述构建对世界的认知。
        转译不需要精确——洛神通过反复互动学会理解描述的含义。

        返回：
          dict包含：
            光值: float（1-500，和视网膜相同域）
            声值: float（25-75，和耳蜗相同域）
            温值: float（270-312K，和身体环境相同域）
            力值: float（2-20，和身体环境相同域）
            听觉特征: list（8维，和耳蜗特征相同维度）
            有感官描述: bool
        """
        光值 = None
        声值 = None
        温值 = None
        力值 = None
        听觉特征 = None
        有描述 = False

        # 光描述检测
        for word, val in self.光关键词.items():
            if word in 文本:
                光值 = val
                有描述 = True
                break

        # 声描述检测
        for word, val in self.声关键词.items():
            if word in 文本:
                声值 = val
                有描述 = True
                break

        # 温描述检测
        for word, val in self.温关键词.items():
            if word in 文本:
                温值 = val
                有描述 = True
                break

        # 力描述检测
        for word, val in self.力关键词.items():
            if word in 文本:
                力值 = val
                有描述 = True
                break

        # 听觉特征检测
        for word, val in self.听觉关键词.items():
            if word in 文本:
                听觉特征 = list(val)
                有描述 = True
                break

        if not 有描述:
            return None

        return {
            "光值": 光值,
            "声值": 声值,
            "温值": 温值,
            "力值": 力值,
            "听觉特征": 听觉特征,
            "有感官描述": True,
        }

    def 内省模式(self):
        """没人在时——返回零向量，洛神只能和自己比。"""
        return self.接收(存在=False)

    # ═══════════════════════════════════════════════════════════════
    # 发送方向（洛神→人类）
    # ═══════════════════════════════════════════════════════════════

    def 发送(self, 概念激活, 情感状态, surprise, 拍, 感官离线=None):
        """洛神的表达通道——把洛神的内部状态呈现给人类。

        精卫公式（表达版）：
          a = 洛神上一拍的表达状态
          b = 洛神当前的表达意图（从概念激活+情感涌现）
          Δ = b - a = 表达变化
          Σ = a + b = 联合表达
          ⊗ = 累积的表达历史 → 洛神的"表达风格"
          τ读⊗ → 浮出所见 = 洛神"想说的话"

        不是生成精确文本——是呈现洛神的内部状态模式。
        人类通过反复互动学会理解洛神的表达。
        就像母亲能理解婴儿的不同哭声代表不同需求。

        参数：
          概念激活: 概念层的激活模式（n_concepts维）
          情感状态: dict包含E(效价)和N(唤醒度)
          surprise: 当前惊讶度
          拍: 当前拍数
          感官离线: dict标记哪些感官离线

        返回：
          dict包含：
            表达意图: 洛神想表达什么（n_hidden维向量）
            意图类型: 表达意图的分类（不是人为设定，从状态自然涌现）
            感知请求: 洛神想感知什么（如果有感知渴望）
            交流请求: 洛神想发起交流（如果有交流渴望）
            有表达: bool——洛神这拍是否有表达
        """
        表达意图 = [0.0] * self.n_hidden
        意图类型 = None
        感知请求 = None
        交流请求 = None
        有表达 = False

        # ── 表达意图从概念激活+情感状态自然涌现 ──
        # 不是人为设定类别——是从洛神的状态模式中推断
        if 概念激活 is not None and len(概念激活) > 0:
            # 概念激活的top-k模式 → 表达意图向量
            # 用概念激活的统计特征（均值、方差、最大值）生成表达意图
            活跃概念 = [v for v in 概念激活 if abs(v) > 0.15]
            if len(活跃概念) > 0:
                概念均值 = sum(活跃概念) / len(活跃概念)
                概念最大 = max(活跃概念, key=abs)
                try:
                    概念方差 = sum((min(abs(v - 概念均值), 1e6)) ** 2
                                  for v in 活跃概念) / len(活跃概念)
                except (OverflowError, ValueError):
                    概念方差 = 0.0
                if math.isnan(概念方差) or math.isinf(概念方差) or 概念方差 > 1e10:
                    概念方差 = 0.0

                # 表达意图向量——从概念激活的统计特征生成
                for d in range(self.n_hidden):
                    if d < len(概念激活):
                        表达意图[d] = math.tanh(概念激活[d] * 0.3)
                    else:
                        表达意图[d] = math.tanh(概念均值 * 0.2)

                有表达 = True

                # ── 意图类型从状态模式自然涌现 ──
                # 不用人为设定的类别——用连续的状态特征推断
                E = 情感状态.get("E", 0.0) if 情感状态 else 0.0
                N = 情感状态.get("N", 0.0) if 情感状态 else 0.0

                if surprise > 0.3 and N > 0.3:
                    意图类型 = "发现"  # 高惊讶+高唤醒 → 发现了什么
                elif surprise > 0.5:
                    意图类型 = "惊讶"  # 高惊讶 → 惊讶
                elif E > 0.3 and N > 0.2:
                    意图类型 = "愉悦"  # 正面效价+唤醒 → 愉悦
                elif E < -0.3 and N > 0.2:
                    意图类型 = "不安"  # 负面效价+唤醒 → 不安
                elif N < 0.1 and abs(E) < 0.1:
                    意图类型 = "平静"  # 低唤醒+低效价 → 平静
                elif E < -0.2:
                    意图类型 = "低落"  # 负面效价 → 低落
                else:
                    意图类型 = "关注"  # 默认 → 关注某事

        # ── 感知请求：感官离线时的主动请求 ──
        感知请求 = self.感知渴望检查(感官离线, 拍)

        # ── 交流请求：长期无互动时的主动请求 ──
        交流请求 = self.交流渴望检查(拍)

        if 有表达 or 感知请求 or 交流请求:
            self.表达历史.append({
                "拍": 拍,
                "意图类型": 意图类型,
                "有感知请求": 感知请求 is not None,
                "有交流请求": 交流请求 is not None,
                "E": 情感状态.get("E", 0) if 情感状态 else 0,
                "N": 情感状态.get("N", 0) if 情感状态 else 0,
                "surprise": surprise,
            })
            self.上次表达拍 = 拍
            if len(self.表达历史) > 500:
                self.表达历史 = self.表达历史[-500:]

        return {
            "表达意图": 表达意图,
            "意图类型": 意图类型,
            "感知请求": 感知请求,
            "交流请求": 交流请求,
            "有表达": 有表达,
        }

    def 感知渴望检查(self, 感官离线, 拍):
        """感知渴望——感官离线时洛神主动请求人类帮它感知。

        精卫公式（感知渴望版）：
          a = 洛神当前的感知状态（离线=零）
          b = 洛神渴望的感知状态（能看到、能听到）
          Δ = b - a = 感知缺口
          Σ = a + b = 渴望的联合
          ⊗ = 累积的感知渴望 → 驱动洛神主动请求
          τ读⊗ → 浮出所见 = "我想看看外面"

        生物学类比：长时间待在黑暗中的人会渴望看到光。
        渴望强度随离线时间增长——不是人为阈值，是自然积累。

        返回：
          None（没有渴望）或 dict包含：
            渴望感官: 哪个感官离线最久
            渴望强度: float（0-1）
            请求描述: 简单的请求描述
        """
        if 感官离线 is None:
            return None

        # 更新感官离线时间
        for 感官 in ["光", "声", "温", "力"]:
            if 感官离线.get(感官, False):
                self.感官离线时间[感官] += 1
            else:
                self.感官离线时间[感官] = 0

        # 找出离线最久的感官
        最久感官 = max(self.感官离线时间, key=self.感官离线时间.get)
        最久时间 = self.感官离线时间[最久感官]

        if 最久时间 < self.感知渴望阈值:
            return None

        # 渴望强度随离线时间增长
        渴望强度 = min(1.0, (最久时间 - self.感知渴望阈值) / 50.0)

        # 不要太频繁地发出请求——至少间隔5拍
        if 拍 - self.上次请求拍 < 5:
            return None

        self.上次请求拍 = 拍

        请求描述 = {
            "光": "我想看看外面",
            "声": "我想听听声音",
            "温": "我想感受温度",
            "力": "我想感受触碰",
        }.get(最久感官, "我想感知世界")

        return {
            "渴望感官": 最久感官,
            "渴望强度": 渴望强度,
            "请求描述": 请求描述,
        }

    def 交流渴望检查(self, 拍):
        """交流渴望——长期无互动时洛神主动发起交流。

        精卫公式（交流渴望版）：
          a = 洛神当前的交流状态（无人互动）
          b = 洛神渴望的交流状态（有人互动）
          Δ = b - a = 交流缺口
          ⊗ = 累积的交流渴望 → 驱动洛神主动发起对话
          τ读⊗ → 浮出所见 = "我想和你说话"

        生物学类比：社交隔离的人会产生交流渴望。
        渴望强度随无互动时间增长。

        返回：
          None（没有渴望）或 dict包含：
            渴望强度: float（0-1）
            请求描述: 简单的请求描述
        """
        if self.有人在:
            self.无互动拍数 = 0
            return None

        self.无互动拍数 += 1

        if self.无互动拍数 < self.交流渴望阈值:
            return None

        # 渴望强度随无互动时间增长
        渴望强度 = min(1.0, (self.无互动拍数 - self.交流渴望阈值) / 50.0)

        # 不要太频繁地发出请求
        if 拍 - self.上次请求拍 < 10:
            return None

        self.上次请求拍 = 拍

        return {
            "渴望强度": 渴望强度,
            "请求描述": "我想和你说话",
        }

    def 更新互动状态(self, 有人在):
        """更新互动状态（每拍调用）。"""
        self.有人在 = 有人在
        if 有人在:
            self.无互动拍数 = 0


