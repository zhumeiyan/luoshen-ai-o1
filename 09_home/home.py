def 读真实温度():
    """读系统热区真实温度（Linux /sys/class/thermal）。

    这是环境自己的物理量。读不到就返回 None——离线，绝不造波动数据。
    返回开尔文。
    """
    热区根 = "/sys/class/thermal"
    try:
        if not os.path.isdir(热区根):
            return None
        最佳 = None
        for 名 in sorted(os.listdir(热区根)):
            路径 = os.path.join(热区根, 名, "temp")
            if os.path.isfile(路径):
                with open(路径) as 文件:
                    毫度 = int(文件.read().strip())
                度 = 毫度 / 1000.0
                if 0 < 度 < 120:
                    最佳 = 度
                    break
        if 最佳 is None:
            return None
        return 最佳 + 273.15
    except Exception:
        return None


class 哈希链:
    """不可篡改的留痕链。这是环境的记忆，也是洛神的记忆。"""

    def __init__(self, 链文件):
        self.链文件 = 链文件
        self.前哈希 = "0" * 64
        if os.path.isfile(链文件):
            try:
                with open(链文件, encoding="utf-8") as 文件:
                    行 = [l for l in 文件.read().splitlines() if l.strip()]
                if 行:
                    self.前哈希 = json.loads(行[-1]).get("hash", self.前哈希)
            except Exception:
                pass

    @staticmethod
    def _json_default(obj):
        """处理numpy类型和其他不可直接JSON序列化的类型。"""
        try:
            import numpy as np
            if isinstance(obj, np.generic):
                return obj.item()
            if isinstance(obj, np.ndarray):
                return obj.tolist()
        except ImportError:
            pass
        if isinstance(obj, set):
            return list(obj)
        raise TypeError(f"Object of type {obj.__class__.__name__} is not JSON serializable")

    def 记(self, 事件, 数据):
        条目 = {
            "timestamp": time.time(),
            "event": 事件,
            "data": 数据,
            "prev_hash": self.前哈希,
        }
        raw = json.dumps(条目, sort_keys=True, ensure_ascii=False, default=self._json_default)
        self.前哈希 = hashlib.sha256(raw.encode()).hexdigest()
        条目["hash"] = self.前哈希
        with open(self.链文件, "a", encoding="utf-8") as 文件:
            文件.write(json.dumps(条目, ensure_ascii=False, default=self._json_default) + "\n")


