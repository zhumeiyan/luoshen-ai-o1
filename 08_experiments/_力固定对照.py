"""三组对照：只喂力通道，固定值。
光=50.0，声=45.0，温=295.0。
力=0.0 / 1.0 / 2.0。
各跑8000拍，种子=1，上限999999。
"""
import random, time
import 身体稳态
from 身体稳态 import 身体

脑大小 = 24
光脑节点 = list(range(脑大小))

def 跑(力值):
    引擎 = 身体(种子=1, 上限满值=999999.0)
    引擎.末梢['声']['低'] = 0.015
    点火 = 0
    亮节点 = set()
    for 拍 in range(8000):
        引擎.环境['光'] = 50.0
        引擎.环境['声'] = 45.0
        引擎.环境['力'] = 力值
        引擎.环境['温'] = 295.0
        引擎.推进()
        for n in 光脑节点:
            if abs(引擎.激活[n]) > 0.5:
                点火 += 1
                亮节点.add(n)
    return 点火, sorted(亮节点)

结果 = {}
for 力 in [0.0, 1.0, 2.0]:
    点火, 节点 = 跑(力)
    结果[力] = (点火, 节点)
    print(f"跑拍数 = 8000")
    print(f"力值 = {力}")
    print(f"光脑点火次数 = {点火}")
    print(f"光脑亮节点列表 = {节点}")
    print()

# 三组对照
节点集 = {f: set(结果[f][1]) for f in [0.0, 1.0, 2.0]}
相同 = 节点集[0.0] & 节点集[1.0] & 节点集[2.0]
不同 = (节点集[0.0] | 节点集[1.0] | 节点集[2.0]) - 相同
print(f"力=0.0亮节点 = {结果[0.0][1]}")
print(f"力=1.0亮节点 = {结果[1.0][1]}")
print(f"力=2.0亮节点 = {结果[2.0][1]}")
print(f"三组亮节点是否相同 = {'是' if 节点集[0.0]==节点集[1.0]==节点集[2.0] else '否'}")
print(f"相同的节点号 = {sorted(相同)}")
print(f"不同的节点号 = {sorted(不同)}")
