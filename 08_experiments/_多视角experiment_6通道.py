"""洛神赋最小多视角实验 —— 6通道版。
新增通道5=位置标记，力通道=10.0不变。
跑8000拍，种子=1，上限999999，声倍数300，声末梢低槛0.015。"""
import os, sys, time, json, random
from collections import Counter

from _多视角引擎_6通道 import 身体

random.seed(1)

# 三个16×16灰度图，模拟杯子三视角
图_正面 = [[0.0]*16 for _ in range(16)]
for r in range(4, 12):
    for c in range(6, 10):
        图_正面[r][c] = 0.9

图_左侧 = [[0.0]*16 for _ in range(16)]
for r in range(3, 13):
    for c in range(2, 8):
        图_左侧[r][c] = 0.85

图_右侧 = [[0.0]*16 for _ in range(16)]
for r in range(3, 13):
    for c in range(8, 14):
        图_右侧[r][c] = 0.85

图片列表 = [图_正面, 图_左侧, 图_右侧]
位置标记 = [0.0, 1.0, 2.0]

引擎 = 身体(种子=1, 上限满值=999999.0)
引擎.末梢['声']['低'] = 0.015
初筋 = len(引擎.筋树)

脑大小 = 引擎.脑大小
光脑节点 = list(range(0, 脑大小))

光脑激活最大 = 0.0
光脑点火 = 0
角度亮节点 = [set(), set(), set()]

for 拍 in range(8000):
    角度序号 = (拍 // 16) % 3
    行号 = 拍 % 16
    图 = 图片列表[角度序号]
    行均值 = sum(图[行号]) / 16.0
    # 光通道 = 画面行均值
    引擎.环境['光'] = 行均值
    # 力通道 = 默认值10.0（不动）
    引擎.环境['力'] = 10.0
    # 声通道 = 声倍数300
    引擎.环境['声'] = 50.0 * 300 / 80 + 引擎.随机器.uniform(-1, 1)
    引擎.环境['温'] = 295.0
    # 位置通道 = 位置标记（索引5）
    引擎._位置输入 = 位置标记[角度序号]
    引擎.推进()
    a = 引擎.激活
    for n in 光脑节点:
        if abs(a[n]) > 光脑激活最大:
            光脑激活最大 = abs(a[n])
        if abs(a[n]) > 0.5:
            光脑点火 += 1
            角度亮节点[角度序号].add(n)

跑拍数 = 8000
净增筋数 = len(引擎.筋树) - 初筋
重叠节点 = set.intersection(*角度亮节点) if all(角度亮节点) else set()

print(f"跑拍数 = {跑拍数}")
print(f"光脑节点激活最大 = {round(光脑激活最大, 4)}")
print(f"光脑点火次数 = {光脑点火}")
print(f"净增筋数 = {净增筋数}")
print(f"角度0亮节点列表 = {sorted(角度亮节点[0])}")
print(f"角度1亮节点列表 = {sorted(角度亮节点[1])}")
print(f"角度2亮节点列表 = {sorted(角度亮节点[2])}")
print(f"三个角度的亮节点，有没有重叠 = {'是' if 重叠节点 else '否'}")
print(f"重叠节点数 = {len(重叠节点)}")
print(f"重叠节点号 = {sorted(重叠节点)}")
