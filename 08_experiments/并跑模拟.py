    print(f"  对照: {社交聚类分(对照日志)}")
    print(f"  前向: {社交聚类分(前向日志)}")
    print(f"  双向: {社交聚类分(双向日志)}")

    def 狗依恋聚类分(日志):
        选序 = [(e["滴"], e["狗需"]) for e in 日志 if e["狗需"]]
