        选序 = [(e["滴"], e["洛神选"]) for e in 日志 if e["洛神选"]]
        if len(选序) < 2: return 0.0
        社交隙 = []; 末 = None
        for 滴, 选 in 选序:
            if 选 == "社交":
                if 末 is not None: 社交隙.append(滴 - 末)
                末 = 滴
        if len(社交隙) < 2: return 0.0
        return sum(1 for g in 社交隙 if g <= 6)

