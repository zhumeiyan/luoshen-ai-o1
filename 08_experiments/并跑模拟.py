        print(f"\n  仅双向洛神翻转 ({len(翻_前向双向)} 滴):")
        for 滴, 前选, 双选 in 翻_前向双向[:15]:
            e = 双向日志[滴]
            dn = e["狗需"] or "-"
            print(f"    滴={滴:3d}  前向={前选:14s}  双向={双选:14s}  狗={dn}  人类活动={e['人类活动']}")

