总滴答 = 180


def 跑模拟(模式="对照", 详报=False):
    """模式: '对照' | '前向' | '双向'"""
    assert 模式 in ("对照", "前向", "双向"), f"未知模式: {模式}"
    环境 = {"光": 50.0, "声": 45.0, "力": 10.0, "温": 295.0}
    洛神 = 身体类(节点数=24, 种子=1)
    洛神.环境 = 环境
    狗儿 = None
    if 模式 != "对照":
        狗儿 = 狗类(3.0, 1, 环境, "小狗")
    # 注: LIFE_SCHEDULES 在新身体里暂无 — 本文件逻辑待交叉验证重新对接
    日志 = []

    for 全局滴 in range(总滴答):
        钟点时 = 全局滴 / 60.0
        狗需求项 = None
        驱动值 = 0.0
        狗表达 = {}

        if 狗儿:
            狗儿.施环境()
            狗结果 = 狗儿.选择()
            狗需求项, 驱动值 = 狗结果 if isinstance(狗结果, tuple) else (狗结果, 0.0)
            if 狗需求项:
                狗儿.服务(狗需求项)
                if 模式 in ("前向", "双向"):
                    狗表达 = 狗儿.表达(狗需求项)
                    for 键, 环键 in [("声", "_狗_声"), ("力", "_狗_力"), ("光", "_狗_光")]:
                        if 键 in 狗表达:
                            环境[键] = max(环境.get(键, 0), 狗表达[键])
                            环境[环键] = 狗表达[键]

        # 狗→洛神 信号衰减
        for k in ("_狗_声", "_狗_力", "_狗_光"):
            if k in 环境:
                环境[k] *= 0.92
                if 环境[k] < 0.3:
                    del 环境[k]

        # 人类→狗 信号衰减
        if "_人类社交活动" in 环境:
            环境["_人类社交活动"] *= 0.95
            if 环境["_人类社交活动"] < 0.03:
                del 环境["_人类社交活动"]

        洛神该滴 = (全局滴 % 3 == 0)
        洛神选 = None
        if 洛神该滴:
            洛神.推进()
            # 新身体无 select/serve — 洛神选择待交叉验证
            if 模式 == "前向" and "_人类社交活动" in 环境:
                del 环境["_人类社交活动"]

        日志.append({
            "滴": 全局滴, "钟点时": round(钟点时, 2),
            "狗需": 狗需求项,
            "洛神选": 洛神选,
            "狗环境": {k.replace("_狗",""): round(环境.get(k,0),1)
                       for k in ("_狗_声","_狗_力","_狗_光") if k in 环境},
            "人类活动": round(环境.get("_人类社交活动", 0), 2),
        })

    return 洛神, 狗儿, 日志


def 计翻转(日志甲, 日志乙, 键="洛神选"):
    """数两个日志之间选择不同的滴数。"""
    翻转 = []
    甲表 = {e["滴"]: e for e in 日志甲}
    乙表 = {e["滴"]: e for e in 日志乙}
    for 滴 in sorted(甲表):
        甲值 = 甲表[滴].get(键)
        乙值 = 乙表.get(滴, {}).get(键)
        if 甲值 is not None and 乙值 is not None and 甲值 != 乙值:
            翻转.append((滴, 甲值, 乙值))
    return 翻转


def 检连段(序列):
    """检连续同选择段。返回 [(选择, 起点, 长), ...]。"""
    if not 序列:
        return []
    段 = []
    前选, 起 = 序列[0][1], 序列[0][0]
    for 滴, 选 in 序列[1:]:
        if 选 != 前选:
            段.append((前选, 起, 滴 - 起))
            前选, 起 = 选, 滴
    段.append((前选, 起, 序列[-1][0] + 1 - 起))
    return 段


