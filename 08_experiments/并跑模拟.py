"""并跑模拟.py — 洛神 + 狗 双向耦合并跑

三个条件:
  A 对照组: 无狗
  B 前向: 狗→洛神 单向耦合 (狗表达调制洛神, 洛神不反馈)
  C 双向:   双向耦合 (洛神 推进(社交) → _人类社交活动 → 狗 依恋/玩耍 ↑)

每条件 180 全局滴答 (洛神滴答 60 次)。
比较 A vs B vs C 的选择序列差异 + 狗的选择序列差异。
"""
