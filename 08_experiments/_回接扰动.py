"""全零输入，第100拍给回接节点一个+0.5脉冲。
自己点禁用，回接差正常。
A组：扰动。B组：不扰动。
跑8000拍。
"""
import 身体稳态
from 身体稳态 import 身体
import numpy as np

def 跑(扰动):
    引擎 = 身体(种子=1, 上限满值=999999.0)
    引擎.末梢['声']['低'] = 0.015
    引擎._自己点 = lambda *a, **k: None
    回接节点 = list(引擎._回接节点)
    非回接节点 = [n for n in range(96) if n not in 回接节点]
    # 选一个回接节点
    目标 = 回接节点[0]
    回接总激活 = {}
    for 拍 in range(1, 8001):
        引擎.环境['光'] = 0.0
        引擎.环境['声'] = 0.0
        引擎.环境['力'] = 0.0
        引擎.环境['温'] = 0.0
        if 扰动 and 拍 == 100:
            引擎.激活[目标] += 0.5
        引擎.推进()
        if (100 <= 拍 <= 200 and 拍 % 10 == 0) or 拍 in [500, 1000, 2000, 4000, 8000]:
            回 = sum(abs(引擎.激活[n]) for n in 回接节点)
            非 = sum(abs(引擎.激活[n]) for n in 非回接节点)
            回接总激活[拍] = {'回接': 回, '非回接': 非}
    return 回接总激活

print("===== A组：扰动 =====")
A = 跑(True)
print(f"第100拍到第200拍，每10拍报：")
for 拍 in range(100, 201, 10):
    print(f"  拍{拍}: 回接节点总激活 = {A[拍]['回接']:.6f} 非回接节点总激活 = {A[拍]['非回接']:.6f}")
print(f"稀疏报点：")
for 拍 in [500, 1000, 2000, 4000, 8000]:
    print(f"  拍{拍}: 回接节点总激活 = {A[拍]['回接']:.6f} 非回接节点总激活 = {A[拍]['非回接']:.6f}")

print()
print("===== B组：不扰动 =====")
B = 跑(False)
for 拍 in [100, 500, 1000, 2000, 4000, 8000]:
    if 拍 in B:
        print(f"  拍{拍}: 回接节点总激活 = {B[拍]['回接']:.6f}")
    else:
        # 拍100不在B的稀疏报点中，需补
        pass

# 补拍100
引擎 = 身体(种子=1, 上限满值=999999.0)
引擎.末梢['声']['低'] = 0.015
引擎._自己点 = lambda *a, **k: None
回接节点 = list(引擎._回接节点)
for 拍 in range(1, 101):
    引擎.环境['光'] = 0.0
    引擎.环境['声'] = 0.0
    引擎.环境['力'] = 0.0
    引擎.环境['温'] = 0.0
    引擎.推进()
print(f"  拍100: 回接节点总激活 = {sum(abs(引擎.激活[n]) for n in 回接节点):.6f}")

print()
print("对照：")
for 拍 in [100, 500, 1000, 2000, 4000, 8000]:
    a = A[拍]['回接'] if 拍 in A else 0
    b = B[拍]['回接'] if 拍 in B else 0
    print(f"  拍{拍}: A组={a:.6f} B组={b:.6f} 差={a-b:.6f}")
