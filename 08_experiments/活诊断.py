import json, sys, os, math, struct, time


def 读波形(路径):
    with open(路径, 'rb') as 文件:
        文件.read(4); 文件.read(4); 文件.read(4)
        原始波形 = None; 采样率 = None; 位宽 = None
        while True:
            块标 = 文件.read(4)
            if len(块标) < 4: break
            块长 = struct.unpack('<I', 文件.read(4))[0]
            if 块标 == b'fmt ':
                格式 = 文件.read(块长)
                采样率 = struct.unpack('<I', 格式[4:8])[0]
                位宽 = struct.unpack('<H', 格式[14:16])[0]
            elif 块标 == b'data':
                原始波形 = 文件.read(块长); break
            else: 文件.read(块长)
    return 原始波形, 采样率, 位宽


def 解码波形(原始波形, 位宽=16):
    点数 = len(原始波形) // 2
    return [采样 / 32780.0 for 采样 in struct.unpack('<{}h'.format(点数), 原始波形)]


列数常量 = 64; 行数常量 = 48
嘴行起 = 23; 嘴行止 = 29; 嘴列起 = 24; 嘴列止 = 34


def 建听觉稀疏(子段):
    点数 = len(子段); 块长 = max(1, 点数 // 列数常量)
    过零列 = []; 能量列 = []
    for 列 in range(列数常量):
        起点 = 列 * 块长; 终点 = min(起点 + 块长, 点数); 块 = 子段[起点:终点]
        if not 块: 过零列.append(0.0); 能量列.append(0.0); continue
        过零数 = sum(1 for 序 in range(1, len(块)) if 块[序-1] >= 0 > 块[序])
        均方 = sum(值*值 for 值 in 块) / len(块)
        过零列.append(float(过零数)); 能量列.append(均方 * 10000)
    return [过零列, 能量列]


def 读像素图(路径):
    with open(路径, 'rb') as 文件:
        魔数 = 文件.readline().strip()
        尺寸行 = 文件.readline().strip()
        while 尺寸行.startswith(b'#'): 尺寸行 = 文件.readline().strip()
        宽, 高 = map(int, 尺寸行.split())
        文件.readline(); 原始数据 = 文件.read()
    if 魔数 == b'P6':
        像素 = [(原始数据[序], 原始数据[序+1], 原始数据[序+2]) for 序 in range(0, len(原始数据), 3)]
        return [[0.299*红 + 0.587*绿 + 0.114*蓝 for 红, 绿, 蓝 in 像素[行*宽:(行+1)*宽]] for 行 in range(高)], 宽, 高
    elif 魔数 == b'P3':
        值列 = [float(值) for 值 in 原始数据.split()]
        return [[0.299*值列[(行*宽+列)*3] + 0.587*值列[(行*宽+列)*3+1] + 0.114*值列[(行*宽+列)*3+2] for 列 in range(宽)] for 行 in range(高)], 宽, 高


def 缩放(源, 目标行=行数常量, 目标列=列数常量):
    if not 源 or not 源[0]: return [[0.0]*目标列 for _ in range(目标行)]
    源行, 源列 = len(源), len(源[0]); 输出 = []
    for 行 in range(目标行):
        浮行 = 行 * 源行 / 目标行; 行0 = int(浮行); 行1 = min(行0 + 1, 源行 - 1); 行小数 = 浮行 - 行0
        输出行 = []
        for 列 in range(目标列):
            浮列 = 列 * 源列 / 目标列; 列0 = int(浮列); 列1 = min(列0 + 1, 源列 - 1); 列小数 = 浮列 - 列0
            像素甲 = 源[行0][列0]; 像素乙 = 源[行0][列1]; 像素丙 = 源[行1][列0]; 像素丁 = 源[行1][列1]
            输出行.append(像素甲*(1-列小数)*(1-行小数) + 像素乙*列小数*(1-行小数) + 像素丙*(1-列小数)*行小数 + 像素丁*列小数*行小数)
        输出.append(输出行)
    return 输出


def 嘴开度(帧):
    累积 = 0.0
    for 行 in range(嘴行起+1, 嘴行止):
        for 列 in range(嘴列起, 嘴列止):
            累积 += abs(帧[行][列] - 帧[行-1][列])
    return 累积


def 提取锚点():
    原始波形, 采样率, 位宽 = 读波形("video_input/audio/speech.wav")
    采样列 = 解码波形(原始波形, 位宽)
    每帧采样 = int(采样率 * 0.10); 帧数 = len(采样列) // 每帧采样

    听觉网格列 = [建听觉稀疏(采样列[帧*每帧采样:(帧+1)*每帧采样]) for 帧 in range(帧数)]

    视觉列 = []
    for 帧号 in range(帧数):
        路径 = os.path.join("video_input/frames", "frame_{:04d}.ppm".format(帧号+1))
        if not os.path.exists(路径): break
        原图, _, _ = 读像素图(路径)
        视觉列.append(缩放(原图, 行数常量, 列数常量))

    帧数 = min(len(听觉网格列), len(视觉列))
    嘴值列 = [嘴开度(视觉列[帧号]) for 帧号 in range(帧数)]
    听觉值列 = []
    for 帧号 in range(1, 帧数):
        当帧 = [值 for 行 in 听觉网格列[帧号] for 值 in 行]
        前帧 = [值 for 行 in 听觉网格列[帧号-1] for 值 in 行]
        听觉值列.append(max(abs(甲-乙) for 甲,乙 in zip(当帧, 前帧)))

    return 嘴值列, 听觉值列, 帧数


def 归一化(值列):
    最小, 最大 = min(值列), max(值列)
    if 最大 == 最小: return [0.5]*len(值列), 最小, 最大
    return [(值-最小)/(最大-最小) for 值 in 值列], 最小, 最大


def 跑甲(嘴归一, 听觉归一, 帧数, 圈数):
    """有噪声，每步记录"""
    嘴 = 嘴归一[0]; 听觉 = 听觉归一[0]
    嘴嘴权, 嘴听权, 嘴外权 = 0.46, 0.22, 0.32
    听听权, 听嘴权, 听外权 = 0.46, 0.22, 0.32

    日志 = []
    步号 = 0
    for 圈 in range(圈数):
        for 序 in range(帧数):
            外嘴 = 嘴归一[序]
            外听 = 听觉归一[序 % len(听觉归一)]

            新嘴 = 嘴嘴权 * 嘴 + 嘴听权 * 听觉 + 嘴外权 * 外嘴
            新听 = 听听权 * 听觉 + 听嘴权 * 嘴 + 听外权 * 外听

            # 噪声
            相位噪声 = 0.001 * math.sin(步号 * 0.37) + 0.001 * math.sin(步号 * 0.11)
            新嘴 += 相位噪声
            新听 += 0.001 * math.cos(步号 * 0.29)

            日志.append({
                "步": 步号, "序": 序,
                "嘴": round(嘴, 6), "听觉": round(听觉, 6),
                "外嘴": round(外嘴, 4), "外听": round(外听, 4),
                "新嘴": round(新嘴, 6), "新听": round(新听, 6),
                "嘴变": round(新嘴 - 嘴, 8), "听变": round(新听 - 听觉, 8),
            })

            嘴, 听觉 = 新嘴, 新听
            步号 += 1

    return 日志


