"""诊断: 追踪学习器 vs 控制组的选择序列。"""
from 身体稳态 import 身体

年龄 = 4.0
节律 = [(0, 24, {"光": 50})]  # 简化占位 (真正的 LIFE_SCHEDULES 在新身体中架构不同)
滴答数 = 200

def 跑轨迹(标签, 含课程):
    身体实例 = 身体(种子=1)
    序列 = []
    for 滴答序 in range(滴答数):
        身体实例.环境["光"] = 50.0
        if 含课程:
            身体实例.环境["光"] += 150
            身体实例.环境["声"] = 身体实例.环境.get("声", 45.0) + 12
            身体实例.环境["力"] = 身体实例.环境.get("力", 10.0) + 7
        身体实例.推进()
        序列.append("-")
    print(f"\n{标签}: {''.join(名[0].upper() if 名 != '-' else '.' for 名 in 序列[:80])}")
    # 计数
    from collections import Counter
    计数 = Counter(序列)
    总计 = sum(计数.values())
    for 键 in ["-", ]:
        print(f"  {键}: {计数[键]} ({100*计数[键]/总计:.1f}%)")

跑轨迹("控制组 (年龄=4, 纯)", 含课程=False)
跑轨迹("学习器 (年龄=4, +课程)", 含课程=True)
