"""只喂光通道，光值恒定=50.0。
其他通道常量：声=45.0，力=10.0，温=295.0。
跑8000拍，种子=1，上限999999。
每1000拍报一次激活统计。
"""
import 身体稳态
import numpy as np
from 身体稳态 import 身体

脑大小 = 24
光脑节点 = list(range(脑大小))
报告拍 = {1000, 2000, 3000, 4000, 5000, 6000, 7000, 8000}

引擎 = 身体(种子=1, 上限满值=999999.0)
引擎.末梢['声']['低'] = 0.015

for 拍 in range(1, 8001):
    引擎.环境['光'] = 50.0
    引擎.环境['声'] = 45.0
    引擎.环境['力'] = 10.0
    引擎.环境['温'] = 295.0
    引擎.推进()
    if 拍 in 报告拍:
        vals = [引擎.激活[n] for n in 光脑节点]
        print(f"第{拍}拍光脑节点激活最大 = {max(vals):.6f}")
        print(f"第{拍}拍光脑节点激活最小 = {min(vals):.6f}")
        print(f"第{拍}拍光脑节点激活平均 = {sum(vals)/len(vals):.6f}")
