"""光脑节点对光/力通道的敏感度测试。
实验A：只喂光通道，光值0→1循环。
实验B：只喂力通道，力值0→2循环。
种子=1，上限999999，声倍数300，声末梢低槛0.015。
跑8000拍。
"""
import os, sys, time, json, random
import 身体稳态
from 身体稳态 import 身体

脑大小 = 24
光脑节点 = list(range(脑大小))

def 跑单通道(通道名, 值序列, 常量字典):
    引擎 = 身体(种子=1, 上限满值=999999.0)
    引擎.末梢['声']['低'] = 0.015
    光脑激活最大 = 0.0
    光脑点火 = 0
    亮节点 = set()
    for 拍 in range(8000):
        引擎.环境['光'] = 常量字典.get('光', 50.0)
        引擎.环境['声'] = 常量字典.get('声', 45.0)
        引擎.环境['力'] = 常量字典.get('力', 10.0)
        引擎.环境['温'] = 常量字典.get('温', 295.0)
        引擎.环境[通道名] = 值序列[拍 % len(值序列)]
        引擎.推进()
        a = 引擎.激活
        for n in 光脑节点:
            if abs(a[n]) > 光脑激活最大:
                光脑激活最大 = abs(a[n])
            if abs(a[n]) > 0.5:
                光脑点火 += 1
                亮节点.add(n)
    return 光脑激活最大, 光脑点火, sorted(亮节点)

光序列 = [i/10.0 for i in range(11)]  # 0.0,0.1,...,1.0
力序列 = [i*2/10.0 for i in range(11)]  # 0.0,0.2,...,2.0

常量_光实验 = {'声': 45.0, '力': 10.0, '温': 295.0}
常量_力实验 = {'光': 50.0, '声': 45.0, '温': 295.0}

print("===== 实验A：只喂光通道 =====")
最大, 点火, 节点 = 跑单通道('光', 光序列, 常量_光实验)
print(f"光脑节点激活最大 = {round(最大, 4)}")
print(f"光脑点火次数 = {点火}")
print(f"光脑亮节点列表 = {节点}")

print("===== 实验B：只喂力通道 =====")
最大, 点火, 节点 = 跑单通道('力', 力序列, 常量_力实验)
print(f"光脑节点激活最大 = {round(最大, 4)}")
print(f"光脑点火次数 = {点火}")
print(f"光脑亮节点列表 = {节点}")
