"""两组对照。
A组：全零输入。
B组：恒定默认输入。
自己点禁用。回接差正常。
各跑8000拍，种子=1，上限999999。
每1000拍报一次四脑激活最大。
"""
import 身体稳态
from 身体稳态 import 身体

脑大小 = 24
脑节点 = {
    '光脑': range(0, 24),
    '声脑': range(24, 48),
    '力脑': range(48, 72),
    '温脑': range(72, 96),
}

def 跑(光, 声, 力, 温):
    引擎 = 身体(种子=1, 上限满值=999999.0)
    引擎.末梢['声']['低'] = 0.015
    引擎._自己点 = lambda *a, **k: None
    结果 = {k: {} for k in 脑节点}
    for 拍 in range(1, 8001):
        引擎.环境['光'] = 光
        引擎.环境['声'] = 声
        引擎.环境['力'] = 力
        引擎.环境['温'] = 温
        引擎.推进()
        if 拍 % 1000 == 0:
            for name, rng in 脑节点.items():
                结果[name][拍] = round(max(abs(引擎.激活[n]) for n in rng), 6)
    return 结果

print("===== A组：全零输入 =====")
A = 跑(0.0, 0.0, 0.0, 0.0)
print(f"跑拍数 = 8000")
print(f"全零输入")
for 拍 in [1000,2000,3000,4000,5000,6000,7000,8000]:
    print(f"第{拍}拍光脑节点激活最大 = {A['光脑'][拍]}")
    print(f"第{拍}拍声脑节点激活最大 = {A['声脑'][拍]}")
    print(f"第{拍}拍力脑节点激活最大 = {A['力脑'][拍]}")
    print(f"第{拍}拍温脑节点激活最大 = {A['温脑'][拍]}")

print()
print("===== B组：恒定输入 =====")
B = 跑(50.0, 45.0, 10.0, 295.0)
print(f"跑拍数 = 8000")
print(f"恒定输入")
for 拍 in [1000,2000,3000,4000,5000,6000,7000,8000]:
    print(f"第{拍}拍光脑节点激活最大 = {B['光脑'][拍]}")
    print(f"第{拍}拍声脑节点激活最大 = {B['声脑'][拍]}")
    print(f"第{拍}拍力脑节点激活最大 = {B['力脑'][拍]}")
    print(f"第{拍}拍温脑节点激活最大 = {B['温脑'][拍]}")

maxA = max(A['光脑'].values())
maxB = max(B['光脑'].values())
print()
print("对照：")
A有激活 = any(v > 0.01 for d in A.values() for v in d.values())
B有激活 = any(v > 0.01 for d in B.values() for v in d.values())
print(f"第一组有没有激活 = {'是' if A有激活 else '否'}")
print(f"第二组有没有激活 = {'是' if B有激活 else '否'}")
print(f"两组激活大小对比 = A组最大{maxA} B组最大{maxB}")
