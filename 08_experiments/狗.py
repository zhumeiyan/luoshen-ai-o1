class 狗:
    """同款基础设施, 不同需求 + 更快时钟。"""

    def __init__(self, 年岁, 滴答分钟=1.0, 环境=None, 名字="小狗"):
        self.年岁 = 年岁
        self.滴答分钟 = 滴答分钟
        self.名字 = 名字
        self.已过分钟 = 0.0

        # 状态变量 — 每种需求一个
        self.状态 = {需: 狗需求[需]["目标值"] for 需 in 狗需求}
        self.已服务数 = {需: 0 for 需 in 狗需求}
        self.不应计时 = {需: 0.0 for 需 in 狗需求}
        self.上次服务 = {需: 0.0 for 需 in 狗需求}

        # 环境 (共享引用 — 与洛神共享同一份)
        self.环境 = 环境 if 环境 is not None else {
            "亮度": 50.0,
            "声响": 45.0,
            "力度": 10.0,
            "温度": 295.0,
        }

        # 内部紧急度 (痕/记忆 — 这里只计数)
        self.痕 = {需: 0 for 需 in 狗需求}

        # 体温抑制累加器 — 依恋服务给它充能,
        # 每滴答衰减。体温 ref 被缩放: base * (1 + K * _依恋热度)
        self._依恋热度 = 0.0

        # 无聊累积: 依恋/玩耍 都在 ref 时充能, 否则衰减
        self._无聊 = 0.0

    def 施环境(self):
        """每滴答调用以推进不应计时器。
        狗没有'节律' — 没有人类强加时间。"""
        for 需 in 狗需求:
            if self.不应计时[需] > 0:
                self.不应计时[需] = max(0.0, self.不应计时[需] - self.滴答分钟)
        # 依恋热度连续衰减 — 0.90/滴答 → 半衰 ~7 滴答
        self._依恋热度 *= 0.90

        # 无聊累积: 依恋 + 追逐 + 玩耍 (非生存) 都在 ref → 无聊↑; 否则衰减
        非生存 = ["依恋", "玩耍", "追逐"]
        总不应 = sum(self.不应计时[需] for 需 in 非生存)
        最大不应 = sum(狗需求[需]["不应分钟"] for 需 in 非生存)  # 25+20+90=135
        阻塞比例 = min(1.0, 总不应 / 最大不应)
        无聊累积率 = 0.03
        无聊衰减率 = 0.06
        self._无聊 += 无聊累积率 * 阻塞比例 - 无聊衰减率 * (1.0 - 阻塞比例)
        self._无聊 = max(0.0, self._无聊)

        # 无聊"烧" ref: 非生存需求的 ref 被无聊按比例侵蚀
        无聊烧蚀率 = 0.3
        烧蚀量 = self._无聊 * 无聊烧蚀率
        for 需 in 非生存:
            if self.不应计时[需] > 0:
                self.不应计时[需] = max(0.0, self.不应计时[需] - 烧蚀量)


    def _漂移(self, 分钟数):
        """环境把状态拉离目标 — 与身体同款。"""
        for 名, 需求 in 狗需求.items():
            状态值 = self.状态[名]

            if 名 == "体温":
                环境温度 = self.环境.get("温度", 311.65)
                冷却率 = 需求["漂移率_每分"] * 分钟数
                # 牛顿冷却 → 拉向环境温度
                温差 = 环境温度 - 状态值
                新值 = 状态值 + 温差 * 冷却率 / (abs(温差) + 1.0) * min(abs(温差), 2.0)
                self.状态[名] = max(308, min(314, 新值))
            elif 名 == "葡萄糖":
                状态值 += 需求["漂移率_每分"] * 分钟数
                self.状态[名] = max(2.0, min(9.0, 状态值))
            else:
                # 向 0 衰减
                状态值 += 需求["漂移率_每分"] * 分钟数
                self.状态[名] = max(0.0, min(1.0, 状态值))

        self.已过分钟 += 分钟数

    def _环境相关(self, 名):
        """狗的感官敏感度:
        - 声响: 更灵敏 (听觉阈 ~15 dB; 人类 ~30)
        - 亮度: 看动更好, 细节稍差 — 权重略低
        - 力度: 类似
        """
        亮度值 = self.环境.get("亮度", 0.0)
        声响值 = self.环境.get("声响", 0.0)
        力度值 = self.环境.get("力度", 0.0)

        亮归一 = min(1.0, max(0.0, (亮度值 - 5.0) / 300.0))
        声归一 = min(1.0, max(0.0, (声响值 - 15.0) / 45.0))     # 狗听更轻
        力归一 = min(1.0, max(0.0, (力度值 - 2.0) / 35.0))

        if 名 == "玩耍":
            return 0.5 * 亮归一 + 0.5 * 声归一
        if 名 == "追逐":
            # 追逐强触发于突变 — 但我们只有瞬时值,
            # 所以用绝对值作为"外面有东西在动/作响"的代理
            return max(亮归一, 声归一)
        if 名 == "依恋":
            return 0.6 * 力归一 + 0.4 * 声归一
        return 0.0

    def _年龄认知(self, 名, 宽幅=1.0):
        """狗年发育。默认宽幅 = 1 年。"""
        起, 止 = 狗需求[名]["发展门"]
        if not (起 <= self.年岁 <= 止):
            return 0.0
        中点 = 起 + 0.3  # 狗发育快 — 认知启动早
        z值 = (self.年岁 - 中点) / 宽幅
        return 1.0 / (1.0 + math.exp(-8.0 * z值))    # 更陡的 sigmoid

    def _无聊驱动(self, 名):
        """无聊积累到一定程度, 直接生成 依恋/玩耍/追逐 驱动。
        连续: tanh 饱和, 依恋最强, 玩耍次之, 追逐最弱。"""
        无聊度 = 无聊驱动上限 * math.tanh(self._无聊 / 无聊饱和)
        if 名 == "依恋":
            return 无聊度
        if 名 == "玩耍":
            return 无聊度 * 0.5
        if 名 == "追逐":
            return 无聊度 * 0.3
        return 0.0

    def _人类耦合(self, 名):
        """从共享环境读取 _人类社交活动。
        当洛神在社交, 狗的依恋/玩耍驱动升高。
        人归一化 [0, 1] — 允许 > 1 (强存在)。"""
        人活动 = self.环境.get("_人类社交活动", 0.0)
        人归一 = min(1.5, max(0.0, 人活动))
        if 名 == "依恋":
            return 0.8 * 人归一
        if 名 == "玩耍":
            return 0.6 * 人归一
        return 0.0

    def _驱动调制(self, 名):
        if 名 in ("体温", "葡萄糖"):
            return 1.0
        基础相关 = self._环境相关(名)
        认知度 = self._年龄认知(名)
        人类耦合 = self._人类耦合(名)
        人类增益 = 4.0
        return 1.0 + 基础相关 * 认知度 + 人类耦合 * 认知度 * 人类增益

    def 驱动(self, 名):
        需求 = 狗需求[名]
        起, 止 = 需求["发展门"]
        if not (起 <= self.年岁 <= 止):
            return -1
        状态值 = self.状态[名]
        目标 = 需求["目标值"]
        # 体温 / 葡萄糖: ref 中 = -1, 不允许与其他需求竞争
        if 名 == "体温":
            if self.不应计时[名] > 0:
                return -1
            状态值 = self.状态[名]
            目标 = 需求["目标值"]
            return abs(状态值 - 目标) * 10
        if 名 == "葡萄糖":
            if self.不应计时[名] > 0:
                return -1
            状态值 = self.状态[名]
            目标 = 需求["目标值"]
            return (需求.get("正常区间", (3.5, 6.5))[0] - 状态值) * 2 if 状态值 < 需求.get("正常区间", (3.5, 6.5))[0] else 0
        # 依恋 / 玩耍 / 追逐: 连续 ref gate
        不应门 = max(0.0, 1.0 - self.不应计时[名])
        基线 = (目标 - 状态值) if 状态值 < 目标 else 0.0
        调制 = self._驱动调制(名)
        人类直驱 = self._人类耦合(名) * self._年龄认知(名)
        基线分量 = (基线 * 调制 + 人类直驱 * 0.3) * 不应门
        # 无聊驱动: 独立通路, 不受 ref 约束 — 无聊到一定程度自己生成需求
        无聊度 = self._无聊驱动(名)
        return 基线分量 + 无聊度

    def 服务(self, 名, 输入增益=1.0):
        需求 = 狗需求[名]
        if self.不应计时[名] > 0:
            return False
        self.已服务数[名] += 1
        if 名 == "体温":
            温差 = 需求["目标值"] - self.状态["体温"]
            self.状态["体温"] += 0.02 * (1 if 温差 > 0 else -1) * min(abs(温差), 1.0) * 输入增益
            self.状态["体温"] = max(308, min(314, self.状态["体温"]))
        elif 名 == "葡萄糖":
            self.状态["葡萄糖"] = min(9.0, self.状态["葡萄糖"] + 需求["恢复_每餐"] * 输入增益)
        elif "恢复_每次" in 需求:
            self.状态[名] = min(1.0, self.状态[名] + 需求["恢复_每次"] * 输入增益)
        elif "恢复_每接触" in 需求:
            self.状态[名] = min(1.0, self.状态[名] + 需求["恢复_每接触"] * 输入增益)

        # 依恋 服务 → 给 _依恋热度 充能 (连续累积, 无 if)
        if 名 == "依恋":
            self._依恋热度 += 0.8   # 每次 依恋 服务充 0.8

        # 连续公式: thermal ref 被 _依恋热度 调制
        基础不应 = 需求["不应分钟"]
        if 名 == "体温":
            依恋热力耦合 = 2.5     # 耦合强度
            self.不应计时["体温"] = 基础不应 * (1.0 + 依恋热力耦合 * self._依恋热度)
        else:
            self.不应计时[名] = 基础不应

        self.上次服务[名] = self.已过分钟
        self.痕[名] += 1
        return True

    def 选择(self):
        最优, 最优驱动 = None, -1
        for 需 in 狗需求:
            d = self.驱动(需)
            if d > 最优驱动:
                最优, 最优驱动 = 需, d
        return 最优, 最优驱动

    def 表达(self, 需求名):
        """此需求被服务时向共享环境输出。
        返回环境增量字典。"""
        增量 = {}
        if 需求名 == "玩耍":
            增量["声"] = 18.0    # play-bark / excited yip
            增量["光"] = 14.0    # rapid movement
        elif 需求名 == "追逐":
            增量["声"] = 28.0    # intense bark
            增量["光"] = 25.0    # fast darting motion
            增量["力"] = 10.0    # brush past
        elif 需求名 == "依恋":
            增量["声"] = 8.0     # soft whimper / lean
            增量["力"] = 22.0    # heavy lean into person
        elif 需求名 == "体温" or 需求名 == "葡萄糖":
            pass   # no audible/visible expression
        return 增量

    def 推进(self):
        """一次滴答: 漂移 + 施环境 + 不应衰减。"""
        self.施环境()
        self._漂移(self.滴答分钟)


def 格式化百分比(计数字典, 键列):
    总 = sum(计数字典.values())
    部件 = []
    for 键 in 键列:
        数 = 计数字典.get(键, 0)
        百分比 = 100.0 * 数 / max(总, 1)
        部件.append(f"{键:>8s}: {数:4d} ({百分比:5.1f}%)")
    return " | ".join(部件)


