"""脸部签名.py — 视频+听觉→方向/分布签名, 无 if-then, 零绝对量纲。

改动:
  1. 相似度 = 球面角距 (arccos) 方向, 不用 L2
  2. 听觉 = 帧内 48 行 × 64 列的实际能量 (每行独立计算, 不再用固定包络)
  3. 听觉签名用"列时间能量分布" (6 段时域 + 过零率), 不用行包络 — 帧间有变化
  4. 视觉 = 相对比值 (上下半/中心-边缘/对称/重心/对比)
"""

import math


# ───────────── 连续工具 ─────────────

def _挤压(值):
    值 = max(-500, min(500, 值))
    return 1.0 / (1.0 + math.exp(-值))


def _整流(值):
    饱和 = 10.0
    return 值 * _挤压(值 * 饱和)


def _安全除(甲, 乙, 精度=1e-9):
    return 甲 / (乙 + 精度)


def _饱和(值, 尺度):
    return 值 / (尺度 + max(0.0, 值))


def _区域均值(网格, 行起, 行止, 列起, 列止):
    行数 = len(网格)
    列数 = max(1, len(网格[0]) if 行数 else 0)
    加权和, 权重和 = 0.0, 0.0
    for 行 in range(max(0, 行起), min(行止, 行数)):
        for 列 in range(max(0, 列起), min(列止, 列数)):
            像素 = 网格[行][列]
            权 = math.exp(-(像素 / 50000.0) ** 2)
            加权和 += 像素 * 权
            权重和 += 权
    return _安全除(加权和, 权重和)


def _余弦(甲向量, 乙向量):
    点积, 模甲, 模乙 = 0.0, 0.0, 0.0
    长 = min(len(甲向量), len(乙向量))
    for 序 in range(长):
        点积 += 甲向量[序] * 乙向量[序]
        模甲 += 甲向量[序] * 甲向量[序]
        模乙 += 乙向量[序] * 乙向量[序]
    模甲, 模乙 = math.sqrt(模甲), math.sqrt(模乙)
    门控 = min(1.0, 模甲) * min(1.0, 模乙)
    return _安全除(点积, 模甲 * 模乙) * 门控


def 签名相似度(甲向量, 乙向量):
    """球面角距相似度: 夹角=arccos(余弦), sim=1-夹角/π。"""
    余弦值 = _余弦(甲向量, 乙向量)
    余弦值 = max(-1.0, min(1.0, 余弦值))
    夹角 = math.acos(余弦值)
    return 1.0 - 夹角 / math.pi


def 签名距离(甲向量, 乙向量):
    相似 = 签名相似度(甲向量, 乙向量)
    return 1.0 - 相似


# ───────────── 听觉矩阵 (每帧独立计算 48×64) ─────────────

def 听觉矩阵(样本, 帧号, 行数=48, 列数=64):
    """对第 帧号 帧 (1600 采样 @16kHz = 100ms), 输出 行数×列数 矩阵。

    每行 = 帧内等分段的实际 RMS dB, 每列 = 时间子窗。
    帧内样本不同 → 行分布不同, 帧间矩阵真正变化。
    """
    起点 = 帧号 * 1600
    # 用帧 + 下一帧的部分做子窗
    总长 = 样本[起点:起点 + 1600]
    矩阵 = [[0.0] * 列数 for _ in range(行数)]

    # 每列的样本偏移 = 起点 + 列 * 每列样本数, 每列样本数 = 25
    每列样本数 = max(1, 1600 // 列数)
    for 列 in range(列数):
        列起点 = 列 * 每列样本数
        for 行 in range(行数):
            # 行 列: 相位滑动
            子起点 = 列起点 + 行 * 3
            子终点 = min(子起点 + 25, len(总长))
            子段 = 总长[子起点:子终点]
            子长 = len(子段)
            if 子长 == 0:
                continue
            均方根 = math.sqrt(sum(采 * 采 for 采 in 子段) / 子长)
            分贝值 = max(0.0, min(60.0, 20.0 * math.log10(均方根 + 1.0)))
            矩阵[行][列] = 分贝值
    return 矩阵


# ───────────── 视觉签名 (6 维相对分布) ─────────────

def 脸部视觉签名(视觉矩阵):
    """6 维相对签名: [上/下半比, 中心边缘比, 对称度, 重心位置, 顶部亮, 相对对比度]。"""
    行数 = len(视觉矩阵)
    列数 = max(1, len(视觉矩阵[0]) * min(1, 行数))

    def 算力(像素):
        return math.exp(-(像素 / 50000.0) ** 2)

    上半均值 = _区域均值(视觉矩阵, 0, 行数 // 2, 0, 列数)
    下半均值 = _区域均值(视觉矩阵, 行数 // 2, 行数, 0, 列数)
    中心均值 = _区域均值(视觉矩阵, 行数 // 4, 3 * 行数 // 4, 列数 // 4, 3 * 列数 // 4)
    边1 = _区域均值(视觉矩阵, 0, 行数 // 8, 0, 列数)
    边2 = _区域均值(视觉矩阵, 7 * 行数 // 8, 行数, 0, 列数)
    边3 = _区域均值(视觉矩阵, 0, 行数, 0, 列数 // 8)
    边4 = _区域均值(视觉矩阵, 0, 行数, 7 * 列数 // 8, 列数)
    边缘均值 = (边1 + 边2 + 边3 + 边4) / 4.0

    上下比 = _安全除(上半均值, 下半均值)
    中心边比 = _安全除(中心均值, 边缘均值)

    # 左右对称
    左加权, 右加权, 左权和, 右权和 = 0.0, 0.0, 0.0, 0.0
    半宽 = 列数 // 2
    for 行 in range(行数):
        for 列方 in range(列数):
            像素 = 视觉矩阵[行][列方]
            权 = 算力(像素)
            是左 = max(0.0, min(1.0, 半宽 - 列方 + 0.5))
            是右 = 1.0 - 是左
            左加权 += 像素 * 权 * 是左
            右加权 += 像素 * 权 * 是右
            左权和 += 权 * 是左
            右权和 += 权 * 是右
    左均值 = _安全除(左加权, 左权和)
    右均值 = _安全除(右加权, 右权和)
    对称度 = 1.0 - abs(左均值 - 右均值) / (左均值 + 右均值 + 1e-6)

    # 垂直重心
    总质量, 加权纵 = 0.0, 0.0
    for 行 in range(行数):
        行质量 = sum(算力(视觉矩阵[行][列方]) for 列方 in range(列数))
        加权纵 += 行 * 行质量
        总质量 += 行质量
    纵重心 = _安全除(加权纵, 总质量) / max(1.0, 行数)

    # 局部对比度 / 均值
    基底亮度 = _区域均值(视觉矩阵, 0, 行数, 0, 列数) + 1e-6
    梯度累积, 梯度权 = 0.0, 0.0
    for 行 in range(行数):
        for 列方 in range(列数 - 1):
            左像素, 右像素 = 视觉矩阵[行][列方], 视觉矩阵[行][列方 + 1]
            权 = math.exp(-((左像素 + 右像素) / 2.0 / 50000.0) ** 2)
            梯度累积 += (abs(左像素 - 右像素) ** 2) * 权
            梯度权 += 权
    相对对比度 = _安全除(math.sqrt(_安全除(梯度累积, 梯度权)), 基底亮度)

    return [上下比, 中心边比, 对称度, 纵重心, _饱和(上半均值, 1000.0), 相对对比度]


# ───────────── 听觉签名 (7 维: 6 时域段 + 过零率) ─────────────

def 脸部听觉签名(听觉矩阵):
    """7 维听觉签名: 列能量 6 段时域分布 + 过零率。"""
    行数 = len(听觉矩阵)
    列数 = max(1, len(听觉矩阵[0]) * min(1, 行数))

    # 列能量 (时间域, 实际帧-帧变化)
    列能量 = []
    for 列方 in range(列数):
        段能量 = 0.0
        for 行 in range(行数):
            段能量 += _整流(听觉矩阵[行][列方])
        列能量.append(段能量 / 行数)

    总能量 = sum(列能量) + 1e-9

    # 6 段时域分布
    段数 = 6
    段宽 = max(1, 列数 // 段数)
    能量分布 = []
    for 段 in range(段数):
        段累积 = sum(列能量[段 * 段宽:(段 + 1) * 段宽])
        能量分布.append(段累积 / 总能量)

    # 时域过零 (连续, 用列能量跳变)
    过零累积 = 0.0
    for 列方 in range(1, len(列能量)):
        跳变 = 列能量[列方] - 列能量[列方 - 1]
        过零累积 += 1.0 / (1.0 + abs(跳变) / 100.0)
    过零率 = 过零累积 / max(1, len(列能量) - 1)

    return 能量分布 + [过零率]


# ───────────── 合并 ─────────────

def 全签名(视觉网格, 听觉网格):
    return 脸部视觉签名(视觉网格) + 脸部听觉签名(听觉网格)


