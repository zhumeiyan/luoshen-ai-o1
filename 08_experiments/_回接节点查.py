"""全零输入对照。
A组：回接差正常。
B组：回接差强制为零。
自己点禁用。种子=1，上限999999。
"""
import 身体稳态
from 身体稳态 import 身体
import numpy as np

def 跑():
    引擎 = 身体(种子=1, 上限满值=999999.0)
    引擎.末梢['声']['低'] = 0.015
    引擎._自己点 = lambda *a, **k: None
    for 拍 in range(8000):
        引擎.环境['光'] = 0.0
        引擎.环境['声'] = 0.0
        引擎.环境['力'] = 0.0
        引擎.环境['温'] = 0.0
        引擎.推进()
    # 回接差已在全0下接近0
    回接 = list(引擎._回接节点)
    非回接 = [n for n in range(96) if n not in 回接]
    激活 = list(引擎.激活)
    回接激活 = [激活[n] for n in 回接]
    非回接激活 = [激活[n] for n in 非回接]
    return {
        '回接平均': float(np.mean([abs(x) for x in 回接激活])),
        '非回接平均': float(np.mean([abs(x) for x in 非回接激活])),
        '回接最大': max(回接激活),
        '回接最小': min(回接激活),
        '非回接最大': max(非回接激活),
        '非回接最小': min(非回接激活),
    }

A = 跑()
print(f"跑拍数 = 8000")
print(f"回接节点（20个）的平均激活 = {A['回接平均']:.6f}")
print(f"非回接节点（76个）的平均激活 = {A['非回接平均']:.6f}")
print(f"回接节点激活最大 = {A['回接最大']:.6f}")
print(f"回接节点激活最小 = {A['回接最小']:.6f}")
print(f"非回接节点激活最大 = {A['非回接最大']:.6f}")
print(f"非回接节点激活最小 = {A['非回接最小']:.6f}")
diff1 = abs(A['回接最大']) - abs(A['回接最小'])
diff2 = A['回接平均'] - A['非回接平均']
print(f"回接节点之间的激活差 = {diff1:.6f}")
print(f"回接节点跟非回接节点的激活差 = {diff2:.6f}")
