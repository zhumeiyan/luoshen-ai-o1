"""三组对照：只喂力通道，力值交替变化。
光=50.0，声=45.0，温=295.0。
力交替每16拍换一次。
各跑8000拍，种子=1，上限999999。
"""
import 身体稳态
from 身体稳态 import 身体

脑大小 = 24
光脑节点 = list(range(脑大小))

def 跑(力低, 力高):
    引擎 = 身体(种子=1, 上限满值=999999.0)
    引擎.末梢['声']['低'] = 0.015
    点火 = 0
    亮节点 = set()
    for 拍 in range(8000):
        引擎.环境['光'] = 50.0
        引擎.环境['声'] = 45.0
        引擎.环境['力'] = 力低 if (拍 // 16) % 2 == 0 else 力高
        引擎.环境['温'] = 295.0
        引擎.推进()
        for n in 光脑节点:
            if abs(引擎.激活[n]) > 0.5:
                点火 += 1
                亮节点.add(n)
    return 点火, sorted(亮节点)

print("第一组：")
点火1, 节点1 = 跑(0.0, 1.0)
print(f"力交替 = 0.0/1.0")
print(f"光脑点火次数 = {点火1}")
print(f"光脑亮节点列表 = {节点1}")

print("第二组：")
点火2, 节点2 = 跑(0.0, 2.0)
print(f"力交替 = 0.0/2.0")
print(f"光脑点火次数 = {点火2}")
print(f"光脑亮节点列表 = {节点2}")

print("第三组：")
点火3, 节点3 = 跑(0.0, 0.1)
print(f"力交替 = 0.0/0.1")
print(f"光脑点火次数 = {点火3}")
print(f"光脑亮节点列表 = {节点3}")

print("对照：")
print(f"三组亮节点是否相同 = {'是' if 节点1==节点2==节点3 else '否'}")
print(f"三组点火次数对比 = 第一组{点火1} 第二组{点火2} 第三组{点火3}")
