def 序列自相关(序列, 滞后):
    """在给定滞后下算序列自相关 (归一化)。"""
    n = len(序列)
    if 滞后 >= n:
        return 0.0
    匹配 = sum(1 for i in range(n - 滞后) if 序列[i] == 序列[i + 滞后])
    return 匹配 / (n - 滞后)


def 序列熵(序列, 字符表):
    """序列的归一化熵。返回 0..1。"""
    from collections import Counter
    if not 序列:
        return 0.0
    计数 = Counter(序列)
    总长 = len(序列)
    H = 0.0
    for 符 in 字符表:
        p = 计数.get(符, 0) / 总长
        if p > 0:
            H -= p * math.log2(p)
    最大熵 = math.log2(len(字符表)) if 字符表 else 1.0
    return H / 最大熵 if 最大熵 > 0 else 0.0


def 跑长程(模式="双向", 天数=总天数, 流文件=None):
    n_ticks = 天数 * 每日滴答
    assert 模式 in ("对照", "前向", "双向")
    环境 = {"光": 50.0, "声": 45.0, "力": 10.0, "温": 295.0}
    洛神 = 身体类(节点数=24, 种子=1)
    洛神.环境 = 环境
    狗儿 = None
    if 模式 != "对照":
        狗儿 = 狗类(3.0, 1, 环境, "小狗")

    # 状态流文件: 每滴答一行 (追加写, 不覆)
    流 = None
    if 流文件 is None:
        流文件 = "/mnt/data/catpaw/home/workspace/洛神赋1.1/状态流.tsv"
    if 流文件:
        import os
        import io
        流 = open(流文件, "w", buffering=1)
        头 = "\t".join([
            "滴", "天", "天内滴", "洛神选",
            "刺体温", "刺探索", "刺社交", "刺葡萄糖"
        ])
        流.write(头 + "\n")

    # 未遂累积 (来自之前的运行)
    未遂文件 = "/mnt/data/catpaw/home/workspace/洛神赋1.1/未遂痕.tsv"
    前未遂 = 0.0
    try:
        with open(未遂文件, "r") as ff:
            行 = ff.readlines()
            if len(行) > 1:
                最后一个 = 行[-1].strip().split("\t")
                前未遂 = float(最后一个[4])
    except (FileNotFoundError, IndexError, ValueError):
        前未遂 = 0.0

    # 每日累加器
    逐日 = []
    今日 = {
        "天": 0, "服务_洛": defaultdict(int), "服务_狗": defaultdict(int),
        "序_洛": [], "序_狗": [], "翻_洛": 0, "翻_狗": 0,
        "无聊_洛总": 0.0, "无聊_洛数": 0,
        "无聊_狗总": 0.0, "无聊_狗数": 0,
        "洛神社交滴": [],
        "狗依恋随洛社交": 0,
        "狗依恋总数": 0,
        "未遂": 0.0, "未遂滴": 0,
    }

    前_洛选 = None
    前_狗选 = None

    for 全局滴 in range(n_ticks):
        天 = 全局滴 // 每日滴答
        天内滴 = 全局滴 % 每日滴答
        洛神选 = None
        洛神它滴 = False

        # 新天边界
        if 天 != 今日["天"]:
            逐日.append(今日)
            # text：压力累积: 前一天未遂 + 历史累积
            运 = 今日.get("未遂", 0.0) + 前未遂
            缩每单位 = 0.3
            总缩 = 运 * 缩每单位
            压力 = min(55.0, 总缩)
            洛神._未遂压 = 压力
            with open(未遂文件, "a") as ff:
                头行 = "天\t想数\t说数\t未遂\t压力\t累积未遂\n"
                import os as _os
                if not _os.path.exists(未遂文件) or _os.path.getsize(未遂文件) == 0:
                    ff.write(头行)
                累积 = 运
                ff.write(f"{今日['天']}\t{今日.get('想数',0)}\t{今日.get('说数',0)}\t{今日['未遂']:.4f}\t{压力:.3f}\t{累积:.4f}\n")
            前未遂 = 运
            今日 = {
                "天": 天, "服务_洛": defaultdict(int), "服务_狗": defaultdict(int),
                "序_洛": [], "序_狗": [], "翻_洛": 0, "翻_狗": 0,
                "无聊_洛总": 0.0, "无聊_洛数": 0,
                "无聊_狗总": 0.0, "无聊_狗数": 0,
                "洛神社交滴": [],
                "狗依恋随洛社交": 0,
                "狗依恋总数": 0,
                "未遂": 0.0, "未遂滴": 0,
            }
            前_洛选 = None
            前_狗选 = None

        狗需 = None
        狗表达 = {}
        狗驱动值 = 0.0

        if 狗儿:
            狗儿.施环境()
            狗结 = 狗儿.选择()
            狗需, 狗驱动值 = 狗结 if isinstance(狗结, tuple) else (狗结, 0.0)
            if 狗需:
                狗儿.服务(狗需)
                狗表达 = 狗儿.表达(狗需) if 模式 == "双向" else {}
                if 模式 == "双向":
                    for 源, 目 in [("声响", "_狗声响"), ("力度", "_狗力度"), ("亮度", "_狗亮度")]:
                        if 源 in 狗表达:
                            环境[源] = max(环境.get(源, 0), 狗表达[源])
                            环境[目] = 狗表达[源]

            # 跟踪狗服务
            if 狗需:
                今日["服务_狗"][狗需] += 1
                今日["序_狗"].append(狗需)
                if 前_狗选 is not None and 狗需 != 前_狗选:
                    今日["翻_狗"] += 1
                前_狗选 = 狗需

            今日["无聊_狗总"] += 狗儿.驱动("依恋")  # 用依恋驱动做代理无聊
            今日["无聊_狗数"] += 1

        # 狗→洛神信号衰减
        for k in ("_狗声响", "_狗力度", "_狗亮度"):
            if k in 环境:
                环境[k] *= 0.92
                if 环境[k] < 0.3:
                    del 环境[k]

        # 人类→狗信号衰减
        if "_人类社交活动" in 环境:
            环境["_人类社交活动"] *= 0.95
            if 环境["_人类社交活动"] < 0.03:
                del 环境["_人类社交活动"]

        洛神它滴 = (全局滴 % 3 == 0)
        if 洛神它滴:
            洛神.推进()
            # 注: HOMEOSTATIC_NEEDS 在新身体无 — 待交叉验证对齐
            洛神选 = None  # 占位: 身体无 select()

        # 双向耦合检测: 如果狗刚服务依恋且洛神在近 15 滴内有社交
        if 狗需 == "依恋" and 今日["洛神社交滴"]:
            最后社交 = max(今日["洛神社交滴"])
            if 0 <= 天内滴 - 最后社交 <= 16:
                今日["狗依恋随洛社交"] += 1
            今日["狗依恋总数"] += 1

        # 状态流: 每滴答一行
        if 流:
            现洛选 = 洛神选 if 洛神选 else "-"
            刺_体温 = float(getattr(洛神, "激活", [0] * 24)[0]) if getattr(洛神, "激活", None) else 0.0
            刺_探索 = float(getattr(洛神, "激活", [0] * 24)[1]) if getattr(洛神, "激活", None) else 0.0
            刺_社交 = float(getattr(洛神, "激活", [0] * 24)[2]) if getattr(洛神, "激活", None) else 0.0
            刺_葡萄糖 = float(getattr(洛神, "激活", [0] * 24)[3]) if getattr(洛神, "激活", None) else 0.0
            行内容 = [
                str(全局滴), str(天), str(天内滴), 现洛选,
                f"{刺_体温:.3f}", f"{刺_探索:.3f}", f"{刺_社交:.3f}", f"{刺_葡萄糖:.3f}"
            ]
            流.write("\t".join(行内容) + "\n")

    # 追加最后一日
    逐日.append(今日)
    if 流:
        流.close()

    return 洛神, 狗儿, 逐日


def 分析(逐日, 模式):
    """分析长跑动态。"""
    print(f"\n{'='*72}")
    print(f"长跑分析 — 模式={模式}, 天数={len(逐日)}")
    print(f"{'='*72}")

    # 每日服务计数 (洛神)
    print(f"\n洛神 每日服务计数:")
    洛神大字 = ["体温", "探索", "社交", "葡萄糖"]
    头行 = f"{'天':>3s}  " + "  ".join(f"{n[:5]:>5s}" for n in 洛神大字) + " 翻转  无聊"
    print("  " + 头行)
    for 日 in 逐日:
        计数 = [日["服务_洛"].get(n, 0) for n in 洛神大字]
        无聊 = 日["无聊_洛总"] / max(1, 日["无聊_洛数"])
        行字 = "  ".join(f"{c:5d}" for c in 计数)
        print(f"  {日['天']:3d}  {行字}  {日['翻_洛']:5d}  {无聊:5.2f}")

    # 每日服务计数 (狗)
    print(f"\n狗 每日服务计数:")
    狗大字 = ["体温", "葡萄糖", "玩耍", "追逐", "依恋"]
    头狗 = f"{'天':>3s}  " + "  ".join(f"{n[:5]:>5s}" for n in 狗大字) + " 翻转  无聊"
    print("  " + 头狗)
    for 日 in 逐日:
        计数 = [日["服务_狗"].get(n, 0) for n in 狗大字]
        无聊 = 日["无聊_狗总"] / max(1, 日["无聊_狗数"])
        行字 = "  ".join(f"{c:5d}" for c in 计数)
        print(f"  {日['天']:3d}  {行字}  {日['翻_狗']:5d}  {无聊:5.2f}")

    # 稳定性分析
    print(f"\n稳定性分析:")
    n = len(逐日)
    三份之一 = n // 3
    if 三份之一 > 0:
        前洛翻 = sum(d["翻_洛"] for d in 逐日[:三份之一]) / 三份之一
        后洛翻 = sum(d["翻_洛"] for d in 逐日[-三份之一:]) / 三份之一
        前狗翻 = sum(d["翻_狗"] for d in 逐日[:三份之一]) / 三份之一
        后狗翻 = sum(d["翻_狗"] for d in 逐日[-三份之一:]) / 三份之一
        print(f"  洛神翻转率 (首{三份之一}天): {前洛翻:.1f}/天 → (末{三份之一}天): {后洛翻:.1f}/天")
        print(f"  狗翻转率   (首{三份之一}天): {前狗翻:.1f}/天 → (末{三份之一}天): {后狗翻:.1f}/天")

    # 熵分析
    洛字表 = ["体温", "探索", "社交", "葡萄糖", "-"]
    狗字表 = ["体温", "葡萄糖", "玩耍", "追逐", "依恋", "-"]
    print(f"\n序列熵 (比特, max=1.0):")
    print(f"  {'天':>3s} 洛神_H  狗_H")
    洛熵集 = []; 狗熵集 = []
    for 日 in 逐日:
        h_l = 序列熵(日["序_洛"], 洛字表)
        h_d = 序列熵(日["序_狗"], 狗字表)
        洛熵集.append(h_l); 狗熵集.append(h_d)
        print(f"  {日['天']:3d}  {h_l:5.3f}  {h_d:5.3f}")

    # 非体温服务占比 (每周)
    print(f"\n非体温服务占比 (每周):")
    周大小 = 7
    for w in range(0, len(逐日), 周大小):
        段 = 逐日[w:w+周大小]
        洛总 = sum(sum(d["服务_洛"].values()) for d in 段)
        洛体 = sum(d["服务_洛"].get("体温", 0) for d in 段)
        洛非 = 1.0 - 洛体 / max(1, 洛总)
        狗总 = sum(sum(d["服务_狗"].values()) for d in 段)
        狗体 = sum(d["服务_狗"].get("体温", 0) for d in 段)
        狗非 = 1.0 - 狗体 / max(1, 狗总)
        print(f"  天 {w:2d}-{w+len(段)-1:2d}: 洛神={洛非:.3f}  狗={狗非:.3f}")

    # 双向耦合分析
    if 模式 == "双向":
        print(f"\n双向耦合 (狗依恋在洛神社交后):")
        for 日 in 逐日:
            n_社 = len(日["洛神社交滴"])
            n_耦 = 日["狗依恋随洛社交"]
            n_总 = 日["狗依恋总数"]
            率 = n_耦 / max(1, n_社) if n_社 > 0 else 0.0
            print(f"    天 {日['天']:2d}: 洛神社交={n_社:2d}  狗依恋总数={n_总:2d}  耦合={n_耦:2d}  率={率:.2f}")

    # 无聊趋势
    print(f"\n无聊均数 (每天):")
    无聊洛 = [d["无聊_洛总"] / max(1, d["无聊_洛数"]) for d in 逐日]
    无聊狗 = [d["无聊_狗总"] / max(1, d["无聊_狗数"]) for d in 逐日]
    if 三份之一 > 0 and 无聊洛:
        前无洛 = sum(无聊洛[:三份之一]) / 三份之一
        后无洛 = sum(无聊洛[-三份之一:]) / 三份之一
        前无狗 = sum(无聊狗[:三份之一]) / 三份之一
        后无狗 = sum(无聊狗[-三份之一:]) / 三份之一
        print(f"  洛神: {前无洛:.2f} → {后无洛:.2f}")
        print(f"  狗:    {前无狗:.2f} → {后无狗:.2f}")

    print(f"\n{'='*72}")
    return 逐日


if __name__ == "__main__":
    import sys
    模式 = sys.argv[1] if len(sys.argv) > 1 else "双向"
