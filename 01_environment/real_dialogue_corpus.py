    def get_all_utterances(self) -> List[str]:
        """获取所有话语。"""
        utterances = []
        for dialogue in self.dialogues:
            for turn in dialogue["轮次"]:
                utterances.append(turn["文本"])
        return utterances
    
    def get_stats(self) -> Dict:
        """统计。"""
        total_dialogues = len(self.dialogues)
        total_turns = sum(len(d["轮次"]) for d in self.dialogues)
        avg_turns = total_turns / total_dialogues if total_dialogues > 0 else 0
        
        # 说话人统计
        speaker_counts = {}
        for dialogue in self.dialogues:
            for turn in dialogue["轮次"]:
                s = turn["说话人"]
                speaker_counts[s] = speaker_counts.get(s, 0) + 1
        
        return {
            "对话数": total_dialogues,
            "总轮次": total_turns,
            "平均每轮": round(avg_turns, 1),
            "说话人分布": speaker_counts,
            "场景": [d["场景"] for d in self.dialogues],
        }


