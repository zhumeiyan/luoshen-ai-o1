# 分岔临界预警
# ═══════════════════════════════════════════════════════════════
# 费根鲍姆常数描述了系统从有序到混沌的分岔过程
# δ = 4.669：分岔间距比——每次分岔的间距缩小δ倍
# α = 2.503：分岔缩放因子——每次分岔的尺度缩小α倍

def 分岔临界度(g):
    """计算当前系统接近费根鲍姆分岔临界点的程度。

    心率旋钮g控制Logistic映射的动力学：
    - g < 3.0：稳定不动点（有序）
    - g = 3.0：第一次分岔（周期2）
    - g ≈ 3.449：第二次分岔（周期4）
    - g ≈ 3.544：第三次分岔（周期8）
    - g ≈ 3.5699...：费根鲍姆点（混沌 onset）
    - g > 3.5699：混沌

    实验数据：痛0.135时g=3.570≈费根鲍姆点——这不是巧合。

    参数：
      g: 当前心率旋钮值

    返回：
      dict包含：
        临界度: 0-1，越接近1越接近混沌
        分岔阶段: '有序'/'周期2'/'周期4'/'周期8'/'混沌'
        距费根鲍姆点: g与3.5699的差距
    """
    FEIGENBAUM_POINT = 3.5699456  # 费根鲍姆点

    if g < 3.0:
        阶段 = '有序'
        临界度 = max(0.0, (g - 1.0) / 2.0)  # 1.0→0, 3.0→1.0
    elif g < 3.449:
        阶段 = '周期2'
        临界度 = 0.5 + (g - 3.0) / (3.449 - 3.0) * 0.2
    elif g < 3.544:
        阶段 = '周期4'
        临界度 = 0.7 + (g - 3.449) / (3.544 - 3.449) * 0.15
    elif g < FEIGENBAUM_POINT:
        阶段 = '周期8'
        临界度 = 0.85 + (g - 3.544) / (FEIGENBAUM_POINT - 3.544) * 0.15
    else:
        阶段 = '混沌'
        临界度 = 1.0

    距费根鲍姆点 = g - FEIGENBAUM_POINT

    return {
        "临界度": round(临界度, 4),
        "分岔阶段": 阶段,
        "距费根鲍姆点": round(距费根鲍姆点, 4),
        "g值": round(g, 4),
    }


def 分岔预警(g, 预测误差=None):
    """当系统接近费根鲍姆分岔临界点时发出预警。

    预警不是人为设定的阈值——是数学常数决定的自然临界点。
    当g接近3.5699（费根鲍姆点）时，系统即将进入混沌。

    参数：
      g: 当前心率旋钮值
      预测误差: 当前预测误差（可选，用于增强预警）

    返回：
      dict包含预警信息
    """
    临界信息 = 分岔临界度(g)

    预警级别 = '正常'
    if 临界信息["临界度"] > 0.95:
        预警级别 = '临界——即将进入混沌'
    elif 临界信息["临界度"] > 0.85:
        预警级别 = '警告——接近分岔临界'
    elif 临界信息["临界度"] > 0.7:
        预警级别 = '注意——已进入分岔区'

    # 如果有预测误差，增强预警——高预测误差+接近临界=更危险
    if 预测误差 is not None:
        pe_rms = math.sqrt(sum(e ** 2 for e in 预测误差) / max(1, len(预测误差)))
        if pe_rms > 0.3 and 临界信息["临界度"] > 0.7:
            预警级别 = '危险——高预测误差+分岔临界'

    return {
        **临界信息,
        "预警级别": 预警级别,
    }


