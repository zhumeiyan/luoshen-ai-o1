import math


# ═══════════════════════════════════════════════════════════════
# 6个核心常数
# ═══════════════════════════════════════════════════════════════

# 拍轴常数
PHI = (1 + math.sqrt(5)) / 2          # φ = 1.618... 黄金比例
T_TRIBONACCI = 1.83928675521416       # T = 1.839... 三波那契常数

# 流轴常数
OMEGA = 0.56714329040978              # Ω = 0.567... Omega常数 (e^(-Ω) = Ω)
G_GLASHER = 2.24000000000000          # G ≈ 2.240 Glaisher-Kinkelin常数

# 分岔常数
DELTA_FEIGENBAUM = 4.66920160910299   # δ = 4.669... 费根鲍姆δ常数
ALPHA_FEIGENBAUM = 2.50290787509589   # α = 2.503... 费根鲍姆α常数

# 派生常数
INV_PHI = 1.0 / PHI                   # 1/φ ≈ 0.618
INV_T = 1.0 / T_TRIBONACCI            # 1/T ≈ 0.544
INV_OMEGA = 1.0 / OMEGA               # 1/Ω ≈ 1.763


# ═══════════════════════════════════════════════════════════════
# 拍轴：学习率演化
# ═══════════════════════════════════════════════════════════════
# 学习率沿拍轴演化：1/φ → 1/T → 1/2
# 早期（高学习率）：快速学习，大量调整
# 中期（1/T）：稳定学习，平衡调整
# 晚期（1/2）：慢速学习，精细调整

def 拍轴学习率(拍, 总拍数=None):
    """学习率沿拍轴演化。

    拍轴：1/φ ≈ 0.618 → 1/T ≈ 0.544 → 1/2 = 0.5

    早期学习率高（快速适应），晚期学习率低（稳定巩固）。
    这不是人为设定的衰减——是数学常数决定的自然演化曲线。

    参数：
      拍: 当前拍数
      总拍数: 预期总拍数（可选，用于确定演化进度）

    返回：
      当前拍的学习率
    """
    if 总拍数 is None or 总拍数 <= 0:
        # 无总拍数时——用对数衰减（幂律而非指数）
        # lr(t) = 1/φ * t^(-log(φ)/log(T))
        # 这给出从1/φ开始，沿拍轴趋向1/T的自然衰减
        progress = 1.0 / (1.0 + math.log(1.0 + 拍) / math.log(T_TRIBONACCI))
        return INV_PHI * progress + INV_T * (1.0 - progress)
    else:
        # 有总拍数时——沿拍轴线性插值
        progress = min(1.0, 拍 / max(1, 总拍数))
        if progress < 0.5:
            # 前半段：1/φ → 1/T
            t = progress * 2.0
            return INV_PHI * (1.0 - t) + INV_T * t
        else:
            # 后半段：1/T → 1/2
            t = (progress - 0.5) * 2.0
            return INV_T * (1.0 - t) + 0.5 * t


def 拍轴衰减率(拍, 总拍数=None):
    """衰减率沿拍轴演化。

    衰减率从1/φ≈0.618开始（快速遗忘），趋向1/T≈0.544（稳定记忆）。
    衰减率越低=遗忘越慢=记忆保持越久。

    参数：
      拍: 当前拍数
      总拍数: 预期总拍数（可选）

    返回：
      当前拍的衰减率（0-1之间，越接近1=衰减越快）
    """
    lr = 拍轴学习率(拍, 总拍数)
    # 衰减率 = 1 - 学习率/φ
    # 早期：lr高→衰减快（1-0.618/1.618≈0.618）
    # 晚期：lr低→衰减慢（1-0.5/1.618≈0.691→不，这个方向不对）
    # 修正：衰减率应该和学习率正相关——高学习率时衰减也快
    # 但衰减率不能太高（否则什么也记不住）
    # 用拍轴映射：衰减率从0.95（早期）趋向0.99（晚期）
    if 总拍数 is None or 总拍数 <= 0:
        progress = 1.0 / (1.0 + math.log(1.0 + 拍) / math.log(T_TRIBONACCI))
    else:
        progress = min(1.0, 拍 / max(1, 总拍数))

    # 衰减率从0.95演化到0.99——越成熟越稳定
    return 0.95 + 0.04 * progress


# ═══════════════════════════════════════════════════════════════
# 流轴：信息流量演化
# ═══════════════════════════════════════════════════════════════
# 流轴：1/Ω ≈ 1.763 → e^s2 → G ≈ 2.240
# 信息流量随系统成熟度增长——从低流量到高流量

def 流轴流量(成熟度):
    """信息流量沿流轴演化。

    流轴：1/Ω ≈ 1.763 → G ≈ 2.240

    参数：
      成熟度: 0-1之间的值，表示系统成熟度

    返回：
      当前流量值
    """
    成熟度 = max(0.0, min(1.0, 成熟度))
    return INV_OMEGA * (1.0 - 成熟度) + G_GLASHER * 成熟度


