# ── 派生常数（整合文档v1.0第四节）──
INV_PHI = 1.0 / PHI                   # 1/φ ≈ 0.618
INV_T = 1.0 / T_TRIBONACCI            # 1/T ≈ 0.543689013 ——差/和比率
INV_OMEGA = 1.0 / OMEGA               # 1/Ω ≈ 1.763

# 收缩率 = √2/T ≈ 0.7689
# 系统在每次循环中收缩的速率——趋向更紧凑的结构
SHRINK_RATE = math.sqrt(2) / T_TRIBONACCI  # √2/T ≈ 0.768892375

# 旋转角 = arctan(1/T) ≈ 32.594°
# 系统在每次循环中旋转的角度——不是直角，是T决定的角度
ROTATION_ANGLE_DEG = math.degrees(math.atan(1.0 / T_TRIBONACCI))  # ≈ 32.593963°
ROTATION_ANGLE_RAD = math.atan(1.0 / T_TRIBONACCI)  # 弧度版

# 自适α* = 1/T² ≈ 0.2956
# 自适应学习率的极限——学习率不能低于此值
SELF_ADAPT_ALPHA = 1.0 / (T_TRIBONACCI ** 2)  # 1/T² ≈ 0.2956

# 孤独税 = 2-T = 1/T³
# 独处时的代谢代价——没有他者时系统需要额外消耗
LONELINESS_TAX = 2.0 - T_TRIBONACCI  # 2-T ≈ 0.1607
LONELINESS_TAX_ALT = 1.0 / (T_TRIBONACCI ** 3)  # 1/T³ ≈ 0.1607（等价表达）

# G^(G-1) = e —— Glaisher-Kinkelin常数与e的关系
# 验证：G^(G-1) ≈ e
G_POWER = G_GLASHER ** (G_GLASHER - 1)  # 应该≈e≈2.718


# ═══════════════════════════════════════════════════════════════
# N波那契家族：T_N → 2
# ═══════════════════════════════════════════════════════════════
# 波那契家族：每个N对应一个常数T_N，当N→∞时T_N→2
# T_2 = φ（黄金比例）——2波那契
# T_3 = T（三波那契）——3波那契
# T_N → 2（N→∞时极限）

def N波那契常数(N):
    """计算N波那契常数T_N。

    N波那契序列：每个数是前N个数的和。
    T_N是N波那契序列的极限比率。

    T_2 = φ ≈ 1.618（黄金比例）
    T_3 ≈ 1.839（三波那契）
    T_N → 2（N→∞时极限）

    精卫公式：a=T_{N-1}, b=T_N, Δ=b-a, Σ=a+b
    Δ>0（T_N随N增大），但Δ递减（趋向2的速率减慢）
    这就是拍轴φ→T→2的数学根源。

    参数：
      N: 波那契序列的阶数（N≥2）

    返回：
      T_N的近似值
    """
    if N < 2:
        return None
    if N == 2:
        return PHI
    if N == 3:
        return T_TRIBONACCI

    # 用迭代法近似T_N
    # T_N满足：T_N^N = T_N^(N-1) + T_N^(N-2) + ... + T_N + 1
    # 即：T_N^N = (T_N^N - 1) / (T_N - 1)（等比数列求和）
    # 化简：T_N^(N+1) - 2*T_N^N + 1 = 0
    # 用牛顿迭代法求解
    x = 1.5  # 初始猜测
    for _ in range(100):
        f = x ** (N + 1) - 2 * x ** N + 1
        fp = (N + 1) * x ** N - 2 * N * x ** (N - 1)
        if abs(fp) < 1e-15:
            break
        x = x - f / fp
    return x


# ═══════════════════════════════════════════════════════════════
# 拍轴：学习率演化
# ═══════════════════════════════════════════════════════════════
# 学习率沿拍轴演化：1/φ → 1/T → 1/2
# 早期（高学习率）：快速学习，大量调整
# 中期（1/T）：稳定学习，平衡调整
# 晚期（1/2）：慢速学习，精细调整

def 拍轴学习率(拍, 总拍数=None):
    """学习率沿拍轴演化。

    拍轴：1/φ ≈ 0.618 → 1/T ≈ 0.544 → 1/2 = 0.5

    早期学习率高（快速适应），晚期学习率低（稳定巩固）。
    这不是人为设定的衰减——是数学常数决定的自然演化曲线。

    参数：
      拍: 当前拍数
      总拍数: 预期总拍数（可选，用于确定演化进度）

    返回：
      当前拍的学习率
    """
    if 总拍数 is None or 总拍数 <= 0:
        # 无总拍数时——用对数衰减（幂律而非指数）
        # lr(t) = 1/φ * t^(-log(φ)/log(T))
        # 这给出从1/φ开始，沿拍轴趋向1/T的自然衰减
        progress = 1.0 / (1.0 + math.log(1.0 + 拍) / math.log(T_TRIBONACCI))
        return INV_PHI * progress + INV_T * (1.0 - progress)
    else:
        # 有总拍数时——沿拍轴线性插值
        progress = min(1.0, 拍 / max(1, 总拍数))
        if progress < 0.5:
            # 前半段：1/φ → 1/T
            t = progress * 2.0
            return INV_PHI * (1.0 - t) + INV_T * t
        else:
            # 后半段：1/T → 1/2
            t = (progress - 0.5) * 2.0
            return INV_T * (1.0 - t) + 0.5 * t


def 拍轴衰减率(拍, 总拍数=None):
    """衰减率沿拍轴演化。

    衰减率从1/φ≈0.618开始（快速遗忘），趋向1/T≈0.544（稳定记忆）。
    衰减率越低=遗忘越慢=记忆保持越久。

    参数：
      拍: 当前拍数
      总拍数: 预期总拍数（可选）

    返回：
      当前拍的衰减率（0-1之间，越接近1=衰减越快）
    """
    lr = 拍轴学习率(拍, 总拍数)
    # 衰减率 = 1 - 学习率/φ
    # 早期：lr高→衰减快（1-0.618/1.618≈0.618）
    # 晚期：lr低→衰减慢（1-0.5/1.618≈0.691→不，这个方向不对）
    # 修正：衰减率应该和学习率正相关——高学习率时衰减也快
    # 但衰减率不能太高（否则什么也记不住）
    # 用拍轴映射：衰减率从0.95（早期）趋向0.99（晚期）
    if 总拍数 is None or 总拍数 <= 0:
        progress = 1.0 / (1.0 + math.log(1.0 + 拍) / math.log(T_TRIBONACCI))
    else:
        progress = min(1.0, 拍 / max(1, 总拍数))

    # 衰减率从0.95演化到0.99——越成熟越稳定
    return 0.95 + 0.04 * progress


