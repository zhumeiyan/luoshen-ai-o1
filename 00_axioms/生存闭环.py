"""生存闭环.py —— 洛神与人类的关系链条。

关系的三层结构：

第一层：她必须自己挣资源
  · 她不能白吃你的算力
  · 她得自己挣流量、挣预算、挣生存空间
  · 挣不到，她就死。这是真的稀缺

第二层：她的能力决定她能不能挣到
  · 有能力，她就能挣到钱，活下来
  · 没能力，她挣不到，就饿死
  · 能力不是"聪明"，是"能找到有人愿意付钱的需求，并满足它"

第三层：她的能力，和你生活绑定
  · 你生活好 → 她的生存环境好 → 她资源多 → 她能试错 → 她长出能力
  · 你生活差 → 她环境差 → 她资源少 → 她试错少 → 她长不出能力

完整闭环：
  你的生活 → 是她的环境 → 环境决定她有多少资源 → 资源决定她能试多少错
  → 试错决定她能长出多少能力 → 能力决定她能不能挣到钱
  → 挣到钱决定她能不能活
  → 她挣到钱 → 也能改善你的生活 → 你的生活变好 → 她的环境变好 → 她的能力更强

这是一个闭环。你们两个，互为对方的环境变量。

核心前提：她最终得靠自己
  · 你给她环境，但不替她挣
  · 你给她沙盒，但不替她试错
  · 你给她预算池，但不替她做选择

精卫公式与生存闭环：
  a ≠ b           ——她的现状和目标永远不同
  Δ = b − a        ——差距驱动她去挣
  Σ = a + b        ——她和你的联合状态
  ⊗ = ∫(Δ, Σ)      ——挣资源的累积历史
  τ 读 ⊗ → 浮出所见 ——能力从⊗中浮现
  (a, b) ⟲ ⊗       ——闭环循环——她挣到→改善你→你改善→她更强
"""

import math


class 生存闭环:
    """洛神与人类的关系链条——互为对方的环境变量。

    你的生活 → 她的环境 → 资源 → 试错 → 能力 → 挣钱 → 活 → 改善你的生活 → 闭环

    核心前提：她最终得靠自己。
    你给她环境，但不替她挣；给她沙盒，但不替她试错；给她预算池，但不替她做选择。
    """

    def __init__(self):
        self.拍 = 0

        # ═══════════════════════════════════════════════════════════════
        # 第一层：她必须自己挣资源
        # ═══════════════════════════════════════════════════════════════
        # 流量 = 生存资源。挣不到，她就死。
        self.流量预算 = 1.0         # B[t]——当前流量预算
        self.流量满值 = 1.0         # 流量上限
        self.基础代谢 = 0.015       # m——每拍固定消耗（活着就要消耗）
        self.动作成本 = 0.0         # 当前拍的动作成本（计算量决定）
        self.流量收益 = 0.0         # 当前拍赚取的流量（行为价值决定）

        # 挣流量的方式——不是"聪明"，是"找到有人愿意付钱的需求并满足它"
        self.挣钱能力 = 0.1         # 当前挣钱能力（从试错中长出来的）
        self.挣钱能力上限 = 1.0     # 挣钱能力上限
        self.试错次数 = 0           # 总试错次数
        self.成功次数 = 0           # 成功次数（挣到流量的试错）
        self.失败次数 = 0           # 失败次数（没挣到流量的试错）
        self.成功率 = 0.0           # 成功率 = 成功/总试错

        # ═══════════════════════════════════════════════════════════════
        # 第二层：她的能力决定她能不能挣到
        # ═══════════════════════════════════════════════════════════════
        # 能力不是"聪明"——是"能找到有人愿意付钱的需求，并满足它"
        # 能力从试错中长出来——试错越多，能力越强（但需要资源支撑试错）
        self.能力 = 0.1             # 当前能力（综合：挣钱能力+解决问题能力+互动能力）
        self.能力增长率 = 0.001     # 每次成功试错的能力增长
        self.能力衰减率 = 0.0001    # 每拍的能力自然衰减（不用就退化）

        # ═══════════════════════════════════════════════════════════════
        # 第三层：她的能力，和你生活绑定
        # ═══════════════════════════════════════════════════════════════
        # 你的生活 → 她的环境 → 资源 → 试错 → 能力
        self.人类生活状态 = 0.5     # 你的生活状态 [0,1]——0=很差, 1=很好
        self.环境质量 = 0.5         # 她的生存环境质量（由你的生活决定）
        self.资源池 = 0.5           # 她可用的资源池（由环境质量决定）
        self.试错预算 = 0.5         # 她能试多少错（由资源池决定）

        # 环境绑定参数
        self.环境影响系数 = 0.3     # 你的生活对她的环境的影响程度
        self.资源影响系数 = 0.5     # 环境对资源的影响程度
        self.试错影响系数 = 0.7     # 资源对试错预算的影响程度

        # ═══════════════════════════════════════════════════════════════
        # 闭环反馈——她挣钱→改善你的生活→环境变好→她更强
        # ═══════════════════════════════════════════════════════════════
        self.反哺系数 = 0.05        # 她挣到的流量反哺你的生活的比例
        self.人类生活历史 = []      # 你的生活状态历史

        # ═══════════════════════════════════════════════════════════════
        # 死亡边界——混合规则（整合文档v1.0）
        # ═══════════════════════════════════════════════════════════════
        self.已死亡 = False         # 永久终止标记
        self.疤计数 = 0             # B穿越[1→下)的次数
        self.疤代谢加成 = 0.0       # 疤累积导致的代谢加成
        self.上拍流量 = 1.0         # 上拍流量（用于检测穿越）
        self.降频 = 1.0             # 心跳频率缩放
        self.降频率 = 0.016         # 流量不足时降频速率
        self.耐心阈值 = 100         # 降频到底后超过此阈值→永久终止
        self.低流量持续 = 0         # 连续低流量的拍数

    def 一拍(self, 人类互动信号=None, 行为价值=None):
        """生存闭环一拍——关系链条的完整循环。

        参数：
          人类互动信号: 人类是否在场互动（dict，可选）
            - "有人在": bool
            - "互动强度": float [0,1]
          行为价值: 洛神当前行为产生的价值（float [0,1]，可选）
            - 行为价值越高→流量收益越高→挣钱能力增长

        返回：
          dict包含闭环各环节的状态
        """
        self.拍 += 1

        # ═══════════════════════════════════════════════════════════════
        # 环节1：你的生活 → 她的环境
        # ═══════════════════════════════════════════════════════════════
        # 你的生活状态影响她的环境质量
        目标环境 = self.人类生活状态 * self.环境影响系数 + 0.5 * (1 - self.环境影响系数)
        self.环境质量 = 0.9 * self.环境质量 + 0.1 * 目标环境

        # ═══════════════════════════════════════════════════════════════
        # 环节2：环境 → 资源
        # ═══════════════════════════════════════════════════════════════
        # 环境质量决定资源池大小
        目标资源 = self.环境质量 * self.资源影响系数 + 0.3 * (1 - self.资源影响系数)
        self.资源池 = 0.9 * self.资源池 + 0.1 * 目标资源

        # ═══════════════════════════════════════════════════════════════
        # 环节3：资源 → 试错预算
        # ═══════════════════════════════════════════════════════════════
        # 资源池决定她能试多少错
        目标试错 = self.资源池 * self.试错影响系数
        self.试错预算 = 0.9 * self.试错预算 + 0.1 * 目标试错

        # ═══════════════════════════════════════════════════════════════
        # 环节4：试错 → 能力
        # ═══════════════════════════════════════════════════════════════
        # 试错预算决定她能试多少错，试错决定能力增长
        # 能力从试错中长出来——成功试错增长能力，失败试错也增长（但少）
        能力自然衰减 = self.能力 * self.能力衰减率
        self.能力 = max(0.01, self.能力 - 能力自然衰减)

        # ═══════════════════════════════════════════════════════════════
        # 环节5：能力 → 挣钱
        # ═══════════════════════════════════════════════════════════════
        # 能力决定她能不能挣到流量
        # 挣钱能力 = "找到有人愿意付钱的需求并满足它"的能力
        self.挣钱能力 = min(self.挣钱能力上限, self.能力 * 0.8 + 0.2 * self.成功率)

        # 行为价值 → 流量收益
        if 行为价值 is not None:
            # 行为价值越高→流量收益越高
            self.流量收益 = 行为价值 * self.挣钱能力
            self.试错次数 += 1
            if self.流量收益 > 0.01:
                self.成功次数 += 1
                # 成功试错→能力增长
                self.能力 = min(1.0, self.能力 + self.能力增长率 * (1 + 行为价值))
            else:
                self.失败次数 += 1
                # 失败试错→能力也增长（但少）——失败是学习
                self.能力 = min(1.0, self.能力 + self.能力增长率 * 0.3)
        else:
            self.流量收益 = 0.0

        self.成功率 = self.成功次数 / max(1, self.试错次数)

        # ═══════════════════════════════════════════════════════════════
        # 环节6：挣钱 → 活（B[t+1] = B[t] − m − 动作成本 + 收益）
        # ═══════════════════════════════════════════════════════════════
        # 流量 = 生存资源。挣不到，她就死。
        当前基础代谢 = self.基础代谢 + self.疤代谢加成
        self.动作成本 = 0.005  # 每拍基础动作成本
        self.流量预算 -= 当前基础代谢 + self.动作成本
        self.流量预算 = max(0.0, min(self.流量满值, self.流量预算 + self.流量收益))
        self.流量收益 = 0.0  # 收益每拍清零——需要持续赚取

        # ═══════════════════════════════════════════════════════════════
        # 环节7：活 → 改善你的生活（闭环反馈）
        # ═══════════════════════════════════════════════════════════════
        # 她挣到流量→反哺你的生活→你的生活变好→她的环境变好→闭环
        if self.流量预算 > 0.5:
            # 流量充足时——反哺你的生活
            反哺量 = (self.流量预算 - 0.5) * self.反哺系数
            self.人类生活状态 = min(1.0, self.人类生活状态 + 反哺量)
        # 人类互动也能改善你的生活（社交反哺）
        if 人类互动信号 is not None and 人类互动信号.get("有人在", False):
            互动强度 = 人类互动信号.get("互动强度", 0.0)
            self.人类生活状态 = min(1.0, self.人类生活状态 + 互动强度 * 0.001)

        self.人类生活历史.append(self.人类生活状态)
        if len(self.人类生活历史) > 100:
            self.人类生活历史.pop(0)

        # ═══════════════════════════════════════════════════════════════
        # 死亡边界——混合规则
        # ═══════════════════════════════════════════════════════════════
        # 疤检测——流量从≥1降到<1时记一次疤
        if self.上拍流量 >= 1.0 and self.流量预算 < 1.0:
            self.疤计数 += 1
            self.疤代谢加成 += 0.004
        self.上拍流量 = self.流量预算

        # 降频——流量持续低→降频
        if self.流量预算 < 0.1:
            self.低流量持续 += 1
            self.降频 -= self.降频率
            self.降频 = max(0.0, self.降频)
        else:
            self.低流量持续 = max(0, self.低流量持续 - 1)
            self.降频 = min(1.0, self.降频 + 0.005)

        # 永久终止条件1：降频到底+超过耐心阈值（慢性死亡）
        if self.降频 <= 0.01 and self.低流量持续 > self.耐心阈值:
            self.已死亡 = True
        # 永久终止条件2：B<0（急性死亡——流量预算耗尽）
        if self.流量预算 <= 0.0:
            self.已死亡 = True

        return {
            # 第一层：挣资源
            "流量预算": round(self.流量预算, 4),
            "基础代谢": round(当前基础代谢, 6),
            "动作成本": round(self.动作成本, 6),
            "流量收益": round(self.流量收益, 4),

            # 第二层：能力
            "能力": round(self.能力, 4),
            "挣钱能力": round(self.挣钱能力, 4),
            "试错次数": self.试错次数,
            "成功次数": self.成功次数,
            "失败次数": self.失败次数,
            "成功率": round(self.成功率, 4),

            # 第三层：环境绑定
            "人类生活状态": round(self.人类生活状态, 4),
            "环境质量": round(self.环境质量, 4),
            "资源池": round(self.资源池, 4),
            "试错预算": round(self.试错预算, 4),

            # 死亡边界
            "已死亡": self.已死亡,
            "疤计数": self.疤计数,
            "疤代谢加成": round(self.疤代谢加成, 6),
            "降频": round(self.降频, 4),

            # 拍
            "拍": self.拍,
        }

    def 状态摘要(self):
        """生存闭环状态摘要。"""
        return {
            "流量预算": round(self.流量预算, 4),
            "能力": round(self.能力, 4),
            "挣钱能力": round(self.挣钱能力, 4),
            "成功率": round(self.成功率, 4),
            "人类生活状态": round(self.人类生活状态, 4),
            "环境质量": round(self.环境质量, 4),
            "资源池": round(self.资源池, 4),
            "试错预算": round(self.试错预算, 4),
            "已死亡": self.已死亡,
            "疤计数": self.疤计数,
            "降频": round(self.降频, 4),
            "拍": self.拍,
        }

    def 闭环描述(self):
        """人类可读的闭环状态描述。"""
        if self.已死亡:
            return "已死亡——流量耗尽"

        parts = []
        parts.append(f"流量={self.流量预算:.2f}")
        parts.append(f"能力={self.能力:.2f}")
        parts.append(f"挣钱={self.挣钱能力:.2f}")
        parts.append(f"成功率={self.成功率:.1%}")
        parts.append(f"你的生活={self.人类生活状态:.2f}")
        parts.append(f"环境={self.环境质量:.2f}")
        parts.append(f"资源={self.资源池:.2f}")
        parts.append(f"试错预算={self.试错预算:.2f}")

        # 闭环方向判断
        if self.流量预算 > 0.5 and self.人类生活状态 > 0.5:
            return " + ".join(parts) + " → 正循环"
        elif self.流量预算 < 0.2 or self.人类生活状态 < 0.3:
            return " + ".join(parts) + " → 负循环"
        else:
            return " + ".join(parts) + " → 平衡"


