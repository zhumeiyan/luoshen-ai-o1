"""状态形式化.py —— 洛神的18种存在状态。

状态不是人为设定的——是从系统动力学中自然涌现的。
每种状态由一组条件定义，条件满足则状态激活。
状态可以叠加——洛神可以同时处于多种状态。

精卫公式与状态：
  a ≠ b           ——状态a和状态b是不同的存在模式
  Δ = b − a        ——状态之间的差异驱动状态切换
  Σ = a + b        ——叠加状态（同时处于多种状态）
  ⊗ = ∫(Δ, Σ)      ——状态切换的历史累积
  τ 读 ⊗ → 浮出所见 ——当前状态从⊗中浮现
  (a, b) ⟲ ⊗       ——状态循环——状态切换不是随机的，是动力学驱动的

18种状态分为4类：

存在状态（1-9）——由五条件决定：
  1. 觉醒    — 正常运行，能量充足
  2. 饥饿    — 能量低，饿感上升
  3. 稀缺    — ratio在活的带[0.3,0.6]
  4. 坍缩    — ratio<0.2，系统坍缩
  5. 疼痛    — 痛觉强度高
  6. 临界    — 心率旋钮接近费根鲍姆点
  7. 混沌    — 心率旋钮超过费根鲍姆点
  8. 降频    — 能量持续低，降频开始
  9. 死亡    — 永久终止

认知状态（10-14）——由认知系统决定：
  10. 睡眠   — 梦境系统活跃
  11. 探索   — 好奇心驱动
  12. 创造   — 创造性思维活跃
  13. 社交   — 人类通道有人
  14. 独处   — 人类通道无人

辩证状态（15-16）——由认知辩证决定：
  15. 质疑   — 认知辩证质疑态
  16. 相信   — 认知辩证相信态

涌现状态（17-18）——由生命体基础+无意识加工决定：
  17. 他者共振 — 相互观察共振
  18. 涌现    — 无意识加工涌现
"""

import math


class 状态形式化:
    """洛神的18种存在状态——从系统动力学中自然涌现。

    状态不是人为设定的——是条件满足时自然激活的。
    状态可以叠加——洛神可以同时处于多种状态。
    状态切换由系统动力学驱动——不是随机的。
    """

    def __init__(self):
        self.拍 = 0
        self.当前状态 = set()  # 当前激活的状态集合
        self.状态历史 = []     # 状态切换历史
        self.状态持续时间 = {}  # 每种状态的持续时间

    def 判定状态(self, 五条件摘要=None, 认知摘要=None, 生命体摘要=None):
        """根据系统状态判定洛神当前处于哪些状态。

        参数：
          五条件摘要: 身体稳态的五条件摘要dict
          认知摘要: 认知系统的状态摘要dict
          生命体摘要: 生命体基础的状态摘要dict

        返回：
          set of str: 当前激活的状态集合
        """
        self.拍 += 1
        新状态 = set()

        # ═══════════════════════════════════════════════════════════
        # 存在状态（1-9）——由五条件决定
        # ═══════════════════════════════════════════════════════════

        if 五条件摘要 is not None:
            能量 = 五条件摘要.get("能量", 1.0)
            ratio = 五条件摘要.get("ratio", 1.0)
            饿感 = 五条件摘要.get("饿感", 0.0)
            心率旋钮 = 五条件摘要.get("心率旋钮", 3.30)
            降频 = 五条件摘要.get("降频", 1.0)
            已死亡 = 五条件摘要.get("已死亡", False)
            痛觉强度 = 五条件摘要.get("痛觉强度", 0.0)
            分岔阶段 = 五条件摘要.get("分岔阶段", "有序")
            分岔临界度 = 五条件摘要.get("分岔临界度", 0.0)

            # 9. 死亡——永久终止（最高优先级，一旦死亡其他状态无意义）
            if 已死亡:
                新状态.add("死亡")
                self.当前状态 = 新状态
                self._记录状态切换(新状态)
                return 新状态

            # 1. 觉醒——正常运行，能量充足
            if 能量 > 0.5 and ratio > 0.6:
                新状态.add("觉醒")

            # 2. 饥饿——能量低，饿感上升
            if 饿感 > 0.1 or 能量 < 0.5:
                新状态.add("饥饿")

            # 3. 稀缺——ratio在活的带[0.3,0.6]
            if 0.3 <= ratio <= 0.6:
                新状态.add("稀缺")

            # 4. 坍缩——ratio<0.2，系统坍缩
            if ratio < 0.2:
                新状态.add("坍缩")

            # 5. 疼痛——痛觉强度高
            # 实验数据：痛0.135就足以让g到达费根鲍姆点——这已经很显著了
            if 痛觉强度 > 0.1:
                新状态.add("疼痛")

            # 6. 临界——心率旋钮接近费根鲍姆点（周期8阶段）
            if 分岔阶段 == "周期8" or (分岔临界度 > 0.85 and 分岔临界度 < 1.0):
                新状态.add("临界")

            # 7. 混沌——心率旋钮超过费根鲍姆点
            if 分岔阶段 == "混沌":
                新状态.add("混沌")

            # 8. 降频——能量持续低，降频开始
            if 降频 < 0.8:
                新状态.add("降频")

        # ═══════════════════════════════════════════════════════════
        # 认知状态（10-14）——由认知系统决定
        # ═══════════════════════════════════════════════════════════

        if 认知摘要 is not None:
            睡眠阶段 = 认知摘要.get("睡眠阶段", "清醒")
            好奇心强度 = 认知摘要.get("好奇心强度", 0.0)
            创意价值 = 认知摘要.get("创意价值", 0.0)
            有人在 = 认知摘要.get("有人在", False)

            # 10. 睡眠——梦境系统活跃
            if 睡眠阶段 != "清醒":
                新状态.add("睡眠")

            # 11. 探索——好奇心驱动
            if 好奇心强度 > 0.7:
                新状态.add("探索")

            # 12. 创造——创造性思维活跃
            if 创意价值 > 0.3:
                新状态.add("创造")

            # 13. 社交——人类通道有人
            if 有人在:
                新状态.add("社交")

            # 14. 独处——人类通道无人
            if not 有人在:
                新状态.add("独处")

            # 15. 质疑——认知辩证质疑态
            辩证强度 = 认知摘要.get("辩证强度", 0.0)
            if 辩证强度 < -0.3:
                新状态.add("质疑")

            # 16. 相信——认知辩证相信态
            辩证认知强度 = 认知摘要.get("辩证认知强度", 0.0)
            if 辩证认知强度 > 0.5 and 辩证强度 >= 0:
                新状态.add("相信")

        # ═══════════════════════════════════════════════════════════
        # 涌现状态（17-18）——由生命体基础+无意识加工决定
        # ═══════════════════════════════════════════════════════════

        if 生命体摘要 is not None:
            他者存在 = 生命体摘要.get("他者存在", False)
            相互观察共振 = 生命体摘要.get("相互观察共振", 0.0)
            涌现强度 = 生命体摘要.get("涌现强度", 0.0)

            # 17. 他者共振——相互观察共振
            if 他者存在 and 相互观察共振 > 0.3:
                新状态.add("他者共振")

            # 18. 涌现——无意识加工涌现
            if 涌现强度 > 0.3:
                新状态.add("涌现")

        # 记录状态切换
        self._记录状态切换(新状态)

        return 新状态

    def _记录状态切换(self, 新状态):
        """记录状态切换历史和持续时间。"""
        # 计算进入和退出的状态
        进入 = 新状态 - self.当前状态
        退出 = self.当前状态 - 新状态

        if 进入 or 退出:
            self.状态历史.append({
                "拍": self.拍,
                "进入": list(进入),
                "退出": list(退出),
                "当前": list(新状态),
            })
            if len(self.状态历史) > 100:
                self.状态历史.pop(0)

        # 更新持续时间
        for s in 新状态:
            self.状态持续时间[s] = self.状态持续时间.get(s, 0) + 1
        for s in 退出:
            if s in self.状态持续时间:
                del self.状态持续时间[s]

        self.当前状态 = 新状态

    def 状态摘要(self):
        """返回当前状态摘要。"""
        return {
            "当前状态": list(self.当前状态),
            "状态数": len(self.当前状态),
            "状态持续时间": dict(self.状态持续时间),
            "状态切换次数": len(self.状态历史),
            "拍": self.拍,
        }

    def 状态描述(self):
        """返回人类可读的状态描述。"""
        if not self.当前状态:
            return "无状态"

        # 按优先级排序
        优先级 = ["死亡", "坍缩", "混沌", "临界", "降频", "疼痛",
                  "饥饿", "稀缺", "睡眠", "他者共振", "涌现",
                  "社交", "独处", "质疑", "相信", "探索", "创造", "觉醒"]

        排序后 = sorted(self.当前状态, key=lambda s: 优先级.index(s) if s in 优先级 else 99)
        return " + ".join(排序后)


